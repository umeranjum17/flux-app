import { describe, it, expect } from 'vitest';
import { fluxAttachmentsSkill } from '../flux-attachments';
import type { SkillContext } from '../types';

function baseCtx(overrides: Partial<SkillContext> = {}): SkillContext {
  return {
    agentId: 'codex',
    mode: 'act',
    isExistingSession: false,
    hasNativeTodoTool: false,
    isAutoGeneratedBranch: false,
    ...overrides,
  };
}

describe('fluxAttachmentsSkill', () => {
  it('is not relevant when attachments are absent', () => {
    expect(fluxAttachmentsSkill.isRelevant(baseCtx())).toBe(false);
  });

  it('is relevant when attachments are present', () => {
    expect(
      fluxAttachmentsSkill.isRelevant(
        baseCtx({
          attachments: { manifestPath: '.context/attachments.json', imageCount: 1, fileCount: 2 },
        }),
      ),
    ).toBe(true);
  });

  it('builds prompt mentioning JSON manifest', () => {
    const prompt = fluxAttachmentsSkill.buildPrompt(
      baseCtx({
        attachments: { manifestPath: '.context/attachments.json', imageCount: 1, fileCount: 2 },
      }),
    );

    expect(prompt).toContain('<flux-skill name="attachments">');
    expect(prompt).toContain('attachments.json');
    expect(prompt).toContain('Images (1)');
    expect(prompt).toContain('File attachments (2)');
    expect(prompt).toContain('</flux-skill>');
  });

  it('omits images section when imageCount is 0', () => {
    const prompt = fluxAttachmentsSkill.buildPrompt(
      baseCtx({
        attachments: { manifestPath: '.context/attachments.json', imageCount: 0, fileCount: 3 },
      }),
    );

    expect(prompt).not.toContain('Images');
    expect(prompt).toContain('File attachments (3)');
  });

  it('omits files section when fileCount is 0', () => {
    const prompt = fluxAttachmentsSkill.buildPrompt(
      baseCtx({
        attachments: { manifestPath: '.context/attachments.json', imageCount: 2, fileCount: 0 },
      }),
    );

    expect(prompt).toContain('Images (2)');
    expect(prompt).not.toContain('File attachments');
  });
});
