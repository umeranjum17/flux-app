import { describe, expect, it } from 'vitest';
import { fluxContextSkill } from '../flux-context';
import type { SkillContext } from '../types';

const baseCtx: SkillContext = {
  agentId: 'codex',
  mode: 'act',
  isExistingSession: false,
  hasNativeTodoTool: false,
  isAutoGeneratedBranch: false,
  workspace: {
    branch: 'flux/test',
    worktreePath: '/repo/.flux/test',
    parentRepo: '/repo',
    outcome: 'in_progress',
  },
};

describe('fluxContextSkill', () => {
  it('is relevant when workspace is present', () => {
    expect(fluxContextSkill.isRelevant(baseCtx)).toBe(true);
  });

  it('is not relevant when workspace is null', () => {
    expect(fluxContextSkill.isRelevant({ ...baseCtx, workspace: undefined })).toBe(false);
  });

  it('lists all context files for any mode', () => {
    for (const mode of ['plan', 'act', 'ask', 'architect'] as const) {
      const prompt = fluxContextSkill.buildPrompt({ ...baseCtx, mode });
      expect(prompt).toContain('session-context.md');
      expect(prompt).toContain('plan.md');
      expect(prompt).toContain('attachments.json');
      expect(prompt).toContain('attachments.md');
      expect(prompt).toContain('attachments/');
    }
  });

  it('includes writing rules for plan and act modes', () => {
    for (const mode of ['plan', 'act'] as const) {
      const prompt = fluxContextSkill.buildPrompt({ ...baseCtx, mode });
      expect(prompt).toContain('### Writing');
      expect(prompt).toContain('mkdir -p .context');
    }
  });

  it('omits writing rules for ask and architect modes', () => {
    for (const mode of ['ask', 'architect'] as const) {
      const prompt = fluxContextSkill.buildPrompt({ ...baseCtx, mode });
      expect(prompt).not.toContain('### Writing');
    }
  });

  it('includes plan persistence instruction only in plan mode', () => {
    const planPrompt = fluxContextSkill.buildPrompt({ ...baseCtx, mode: 'plan' });
    expect(planPrompt).toContain('persist it to `.context/plan.md`');

    const actPrompt = fluxContextSkill.buildPrompt({ ...baseCtx, mode: 'act' });
    expect(actPrompt).not.toContain('persist it to `.context/plan.md`');
  });

  it('wraps output in flux-skill tags', () => {
    const prompt = fluxContextSkill.buildPrompt(baseCtx);
    expect(prompt).toContain('<flux-skill name="context">');
    expect(prompt).toContain('</flux-skill>');
  });
});
