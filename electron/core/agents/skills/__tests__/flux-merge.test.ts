import { describe, expect, it } from 'vitest';
import { fluxMergeSkill } from '../flux-merge';

describe('fluxMergeSkill', () => {
  it('keeps merge execution inside the worktree', () => {
    const prompt = fluxMergeSkill.buildPrompt({
      agentId: 'codex',
      mode: 'act',
      workspaceAction: 'merge',
      isExistingSession: false,
      hasNativeTodoTool: false,
      isAutoGeneratedBranch: false,
      merge: {
        targetBranch: 'master',
        squash: false,
      },
      workspace: {
        branch: 'flux/fix-merge-flow',
        worktreePath: '/repo/.flux/fix-merge-flow',
        parentRepo: '/repo',
        outcome: 'in_progress',
      },
    });

    expect(prompt).toContain('Run every git command from the workspace worktree');
    expect(prompt).toContain('git pull --no-rebase origin master');
    expect(prompt).toContain('git push origin HEAD:master');
    expect(prompt).not.toContain('git checkout master');
    expect(prompt).not.toContain('Run the merge from the parent repo');
  });

  it('describes squash handling without checking out the target branch', () => {
    const prompt = fluxMergeSkill.buildPrompt({
      agentId: 'codex',
      mode: 'act',
      workspaceAction: 'merge',
      isExistingSession: false,
      hasNativeTodoTool: false,
      isAutoGeneratedBranch: false,
      merge: {
        targetBranch: 'main',
        squash: true,
      },
      workspace: {
        branch: 'flux/fix-merge-flow',
        worktreePath: '/repo/.flux/fix-merge-flow',
        parentRepo: '/repo',
        outcome: 'in_progress',
      },
    });

    expect(prompt).toContain('git reset --soft origin/main');
    expect(prompt).toContain('git push origin HEAD:main');
    expect(prompt).not.toContain('git checkout main');
  });
});
