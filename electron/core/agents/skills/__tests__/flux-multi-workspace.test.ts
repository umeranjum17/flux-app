import { describe, expect, it } from 'vitest';

import { fluxMultiWorkspaceSkill } from '../flux-multi-workspace';
import type { SkillContext } from '../types';

const baseCtx: SkillContext = {
  agentId: 'codex',
  mode: 'act',
  isExistingSession: false,
  hasNativeTodoTool: false,
  isAutoGeneratedBranch: false,
  workspace: {
    branch: 'flux/current-task',
    worktreePath: '/repo/.flux/current-task',
    parentRepo: '/repo',
    outcome: 'in_progress',
  },
  siblingWorkspaces: [
    {
      worktreePath: '/repo-a/.flux/api-change',
      parentRepo: '/repo-a',
      branch: 'flux/api-change',
      label: 'API Change',
      role: 'sibling',
      outcome: 'ready_for_pr',
    },
    {
      worktreePath: '/repo-b/.flux/ui-update',
      parentRepo: '/repo-b',
      branch: 'flux/ui-update',
      label: 'UI Update',
      role: 'sibling',
      outcome: 'in_progress',
    },
  ],
};

describe('fluxMultiWorkspaceSkill', () => {
  it('is relevant only when linked sibling workspaces exist', () => {
    expect(fluxMultiWorkspaceSkill.isRelevant(baseCtx)).toBe(true);
    expect(fluxMultiWorkspaceSkill.isRelevant({ ...baseCtx, siblingWorkspaces: undefined })).toBe(false);
    expect(fluxMultiWorkspaceSkill.isRelevant({ ...baseCtx, siblingWorkspaces: [] })).toBe(false);
  });

  it('includes sibling outcomes and agent-agnostic repo instructions', () => {
    const prompt = fluxMultiWorkspaceSkill.buildPrompt(baseCtx);

    expect(prompt).toContain('## Linked Repositories');
    expect(prompt).toContain('Outcome: ready_for_pr');
    expect(prompt).toContain('Outcome: in_progress');
    expect(prompt).toContain('You have **full read and write access** to all linked repos');
    expect(prompt).toContain('absolute paths');
    expect(prompt).toContain('AGENTS.md');
    expect(prompt).toContain('CLAUDE.md');
  });

  it('switches to planning guidance in plan mode', () => {
    const prompt = fluxMultiWorkspaceSkill.buildPrompt({ ...baseCtx, mode: 'plan' });

    expect(prompt).toContain('Call out cross-repo dependencies explicitly');
    expect(prompt).toContain('what kind (new files, API changes, config updates, etc.)');
    expect(prompt).not.toContain('full read and write access');
  });
});
