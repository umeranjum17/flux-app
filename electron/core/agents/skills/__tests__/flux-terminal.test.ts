import { describe, expect, it } from 'vitest';

import { fluxTerminalSkill } from '../flux-terminal';
import type { SkillContext } from '../types';

const baseCtx: SkillContext = {
  agentId: 'codex',
  mode: 'act',
  isExistingSession: false,
  hasNativeTodoTool: false,
  isAutoGeneratedBranch: false,
  workspace: {
    branch: 'flux/test',
    worktreePath: '/repo/.flux/test',
    parentRepo: '/repo',
    outcome: 'in_progress',
  },
};

describe('fluxTerminalSkill', () => {
  it('is only relevant for act-mode workspace tasks', () => {
    expect(fluxTerminalSkill.isRelevant(baseCtx)).toBe(true);
    expect(fluxTerminalSkill.isRelevant({ ...baseCtx, mode: 'plan' })).toBe(false);
    expect(fluxTerminalSkill.isRelevant({ ...baseCtx, workspace: undefined })).toBe(false);
  });

  it('distinguishes captured exec output from visible terminal spawns', () => {
    const prompt = fluxTerminalSkill.buildPrompt(baseCtx);

    expect(prompt).toContain('it does not create a live visible terminal tab');
    expect(prompt).toContain('Use `terminal:spawn` whenever terminal visibility matters');
    expect(prompt).toContain('tests, typechecks, and final checks');
    expect(prompt).toContain('"command": "npm test"');
  });
});
