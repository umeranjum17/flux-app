import { describe, expect, it } from 'vitest';
import { fluxWorkspaceSkill } from '../flux-workspace';

describe('fluxWorkspaceSkill', () => {
  it('puts workspace naming guidance first for auto-generated workspaces', () => {
    const prompt = fluxWorkspaceSkill.buildPrompt({
      agentId: 'codex',
      mode: 'act',
      isExistingSession: false,
      hasNativeTodoTool: false,
      isAutoGeneratedBranch: true,
      workspace: {
        branch: 'flux/workspace-a1b2c3',
        worktreePath: '/repo/.flux/worktree-a1b2c3',
        parentRepo: '/repo',
        outcome: 'in_progress',
      },
    });

    const workspaceNamingIdx = prompt.indexOf('## Workspace Naming');
    const workspaceContextIdx = prompt.indexOf('## Workspace Context');
    expect(workspaceNamingIdx).toBeGreaterThan(-1);
    expect(workspaceContextIdx).toBeGreaterThan(-1);
    expect(workspaceNamingIdx).toBeLessThan(workspaceContextIdx);
    expect(prompt).toContain('.context/state.json');
    expect(prompt).toContain('workspace_name');
  });

  it('skips workspace naming for resumed sessions', () => {
    const prompt = fluxWorkspaceSkill.buildPrompt({
      agentId: 'codex',
      mode: 'act',
      isExistingSession: true,
      hasNativeTodoTool: false,
      isAutoGeneratedBranch: true,
      workspace: {
        branch: 'flux/workspace-a1b2c3',
        worktreePath: '/repo/.flux/worktree-a1b2c3',
        parentRepo: '/repo',
        outcome: 'in_progress',
      },
    });

    expect(prompt).not.toContain('## Workspace Naming');
  });

  it('skips workspace naming for non-auto-generated branches', () => {
    const prompt = fluxWorkspaceSkill.buildPrompt({
      agentId: 'codex',
      mode: 'act',
      isExistingSession: false,
      hasNativeTodoTool: false,
      isAutoGeneratedBranch: false,
      workspace: {
        branch: 'flux/fix-token-refresh',
        worktreePath: '/repo/.flux/fix-token-refresh',
        parentRepo: '/repo',
        outcome: 'in_progress',
      },
    });

    expect(prompt).not.toContain('## Workspace Naming');
  });
});
