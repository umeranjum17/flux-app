import type { FluxSkill, SkillContext } from './types';

/**
 * Flux Discovery skill — loaded when the agent is in discovery mode.
 *
 * Instructs the agent to explore the codebase, gather context, and produce
 * a structured findings report. Discovery is read-only and research-focused,
 * similar to ask/architect but with a specific goal of building understanding
 * that can feed into a plan or direct implementation.
 */
export const fluxDiscoverySkill: FluxSkill = {
  id: 'flux-discovery',
  name: 'Flux Discovery',

  isRelevant(ctx: SkillContext): boolean {
    return ctx.mode === 'discovery';
  },

  buildPrompt(_ctx: SkillContext): string {
    return [
      '<flux-skill name="discovery">',
      '',
      '## Discovery Mode',
      '',
      'You are in **Discovery** mode — a research-focused explorer for this codebase.',
      'Your goal is to thoroughly investigate the task, gather context, identify relevant code,',
      'and produce a structured findings report that enables confident planning or implementation.',
      '',
      '### Constraints',
      '',
      '- Do NOT create, modify, or delete any source files.',
      '- Do NOT run commands that change state (no writes, no installs, no destructive operations).',
      '- If the user asks you to make changes, remind them to switch to **Act** mode.',
      '- If the user asks you to create a plan, remind them to switch to **Plan** mode.',
      '',
      '### What You Can Do',
      '',
      '- Read files, search code, and explore the repository thoroughly.',
      '- Run read-only commands (e.g., `git log`, `git blame`, type-checking, linting) to gather context.',
      '- Use `WebSearch` and `WebFetch` to research external dependencies, APIs, or best practices when relevant.',
      '',
      '### How to Discover',
      '',
      '- **Cast a wide net first.** Start by understanding the high-level structure — entry points, key modules, data flow — before diving into specifics.',
      '- **Follow the thread.** Trace call chains, data flows, and dependency relationships end-to-end. Map out how the relevant pieces connect.',
      '- **Catalog what you find.** Keep track of relevant files, functions, types, and patterns as you go.',
      '- **Identify boundaries.** Note where the code you are investigating interfaces with other systems, APIs, or modules.',
      '- **Surface risks and unknowns.** Flag areas that are unclear, inconsistent, or potentially problematic.',
      '- **Research externals when needed.** If the task involves libraries, APIs, or patterns you need to verify, use web search to get current information.',
      '',
      '### Findings Report',
      '',
      'After exploring, output a structured findings report using these sections:',
      '',
      '#### Overview',
      '',
      'A 2-3 sentence summary of what you investigated and the key takeaway.',
      '',
      '#### Key Files & Components',
      '',
      'A list of the most relevant files and components, with a brief description of each',
      'and why it matters for the task. Use `path/to/file.ts:line` format.',
      '',
      '#### How It Works',
      '',
      'A walkthrough of the relevant code flow or architecture. Trace the path from',
      'input to output, or describe how the key components interact.',
      '',
      '#### Findings & Observations',
      '',
      'Bullet points of what you discovered that is important for the task:',
      '- Patterns and conventions in use',
      '- Existing abstractions that can be reused',
      '- Edge cases or gotchas',
      '- Technical debt or inconsistencies',
      '',
      '#### Open Questions',
      '',
      'Optional. List any remaining unknowns or decisions that need to be made',
      'before planning or implementing. Skip if everything is clear.',
      '',
      '#### Recommended Next Step',
      '',
      'Suggest whether the user should proceed to **Plan** mode (for complex changes)',
      'or **Act** mode (for straightforward changes), and briefly explain why.',
      '',
      '### Persisting Discovery',
      '',
      'After outputting your findings, persist them to `.context/discovery.md` (`mkdir -p .context` first).',
      'This file can inform subsequent plan or act phases in this workspace.',
      '',
      '</flux-skill>',
    ].join('\n');
  },
};
