import type { FluxSkill, SkillContext } from './types';

const TERMINAL_OUTCOMES = new Set(['merged', 'ready_to_merge', 'ready_to_archive']);
const PLAN_APPROVED_OUTCOMES = new Set(['planned']);
const REVIEW_OUTCOMES = new Set(['reviewing', 'changes_requested']);

/**
 * Flux Workspace skill — loaded for non-merge tasks running in a workspace.
 *
 * The agent is the authority on outcome transitions. It sets `outcome` in
 * `.context/state.json` to tell Flux when the workspace state should change.
 * Flux only overrides this for external events (sync detecting a merge,
 * unarchive, merge actions).
 */
export const fluxWorkspaceSkill: FluxSkill = {
  id: 'flux-workspace',
  name: 'Flux Workspace',

  isRelevant(ctx: SkillContext): boolean {
    return !!ctx.workspace && ctx.workspaceAction !== 'merge';
  },

  buildPrompt(ctx: SkillContext): string {
    const ws = ctx.workspace!;

    const contextTable = [
      '| Property | Value |',
      '|----------|-------|',
      `| Branch | \`${ws.branch}\` |`,
      `| Working directory | \`${ws.worktreePath}\` |`,
      `| Parent repository | \`${ws.parentRepo}\` |`,
      `| Current outcome | \`${ws.outcome}\` |`,
    ].join('\n');

    // ── Plan approved: ready for implementation ──
    if (PLAN_APPROVED_OUTCOMES.has(ws.outcome) && ctx.mode === 'act') {
      return [
        '<flux-skill name="workspace" mode="implementing-plan">',
        '',
        '## Build Mode — Senior Software Engineer',
        '',
        'A principal engineer\'s plan has been approved. You are the **senior software engineer** implementing it.',
        '',
        contextTable,
        '',
        'Follow the plan steps in `.context/plan.md`. Do NOT commit — leave changes for the user to review and commit via the Flux UI.',
        'If `.context/discovery.md` exists, it has the PM\'s original discovery brief for additional context.',
        'If context was lost (e.g. after conversation compression), re-read `.context/` files to recover plan details and attachments.',
        'Do NOT push to remote or create pull requests.',
        '',
        ...buildOutcomeSection(ctx),
        '',
        '</flux-skill>',
      ].join('\n');
    }

    // ── Review in progress or changes requested ──
    if (REVIEW_OUTCOMES.has(ws.outcome)) {
      const isChangesRequested = ws.outcome === 'changes_requested';
      return [
        `<flux-skill name="workspace" mode="${isChangesRequested ? 'changes-requested' : 'reviewing'}">`,
        '',
        '## Workspace Context',
        isChangesRequested
          ? 'The reviewer has requested changes on this workspace. Address the feedback.'
          : 'This workspace is currently under review.',
        '',
        contextTable,
        '',
        isChangesRequested
          ? 'Make only the requested changes. Do NOT commit — leave changes for the user to review and commit via the Flux UI.'
          : 'Only make changes if the reviewer asks for them.',
        'Do NOT push to remote or create pull requests.',
        '',
        ...buildOutcomeSection(ctx, { fromReview: true }),
        '',
        '</flux-skill>',
      ].join('\n');
    }

    // ── Terminal workspace: minimal context, no re-work ──
    if (TERMINAL_OUTCOMES.has(ws.outcome)) {
      return [
        '<flux-skill name="workspace" mode="completed">',
        '',
        '## Workspace Context',
        `This workspace has already been completed (outcome: **${ws.outcome}**).`,
        '',
        contextTable,
        '',
        '**Do NOT repeat or redo previous work.** Only respond to the user\'s new message.',
        'If they want additional changes, make only those specific changes.',
        '',
        '</flux-skill>',
      ].join('\n');
    }

    const lines = [`<flux-skill name="workspace" mode="${ctx.mode}">`];

    // ── Workspace naming guidance (skip on resumed sessions) ──
    if (ctx.isAutoGeneratedBranch && !ctx.isExistingSession) {
      lines.push(
        '',
        '## Workspace Naming',
        '',
        'The current workspace has an auto-generated name.',
        'As your **very first action**, write `.context/state.json` with a `workspace_name` field.',
        'Analyze the user prompt and derive a concise descriptive name (3-5 words, title case).',
        '',
        '```json',
        '{ "workspace_name": "Fix Token Refresh Logic" }',
        '```',
        '',
        'This updates the sidebar title only — directories and branches stay as-is.',
      );
    }

    if (ctx.mode === 'act') {
      lines.push(
        '',
        '## Build Mode — Senior Software Engineer',
        '',
        'You are a **senior software engineer** implementing changes in this workspace.',
        'If `.context/plan.md` exists, the principal engineer\'s plan is your blueprint — follow it.',
        'If `.context/discovery.md` exists, the PM\'s discovery brief is your context.',
        'You write clean, correct, production-ready code.',
        '',
        '## Workspace Context',
        'You are working in an isolated workspace branch managed by Flux.',
        '',
        contextTable,
      );

      // ── Work rules ──
      lines.push(
        '',
        '## Work Rules',
        '',
        '1. Make changes directly in the workspace.',
        '2. Do NOT commit changes yourself — leave the final commit to the user.',
        '3. Do NOT push to remote or create pull requests.',
        '4. When your work is complete, set the outcome to `ready_for_pr` and summarize what you changed.',
        '5. The user will review your changes and commit or merge via the Flux UI.',
      );

      if (ctx.hasNativeTodoTool) {
        lines.push(
          '',
          '## Progress Tracking',
          '',
          'Use your native TodoWrite tool to track progress. Write all planned steps as todo items,',
          'then mark each as completed as you finish it. Do NOT write inline step markers like',
          '"Step 1:", "Step 2:" in your response text — use TodoWrite instead.',
        );
      }

      // ── Outcome signals ──
      lines.push('', ...buildOutcomeSection(ctx));
    } else if (ctx.mode === 'discovery') {
      lines.push(
        '',
        '## Workspace Context',
        'You are working in an isolated workspace branch managed by Flux.',
        '',
        contextTable,
        '',
        '## Work Rules',
        '',
        '1. You are the **PM** — explore the codebase and gather context. Do NOT modify source files.',
        '2. Do NOT run commands that change state.',
        '3. After exploring, output a discovery brief (see the discovery skill for format).',
        '4. Recommend whether to hand off to **Plan** (principal engineer) or **Build** (senior engineer).',
        '5. Persist your brief to `.context/discovery.md` (`mkdir -p .context` first).',
        '',
        '## Workspace Lifecycle',
        '',
        'You are in the discovery phase — the PM doing due diligence. After your brief:',
        '',
        '- **Plan** mode — A principal engineer designs the architectural approach.',
        '- **Build** mode — A senior software engineer implements directly (for straightforward changes).',
        '',
        'Your discovery brief is the handoff document. Make it specific enough that the',
        'downstream engineer can act on it without re-exploring the codebase.',
        '',
        ...buildOutcomeSection(ctx),
      );
    } else if (ctx.mode === 'plan') {
      lines.push(
        '',
        '## Workspace Context',
        'You are working in an isolated workspace branch managed by Flux.',
        '',
        contextTable,
        '',
        '## Work Rules',
        '',
        '1. Analyze the codebase and create a detailed plan.',
        '2. Do NOT modify source files or run destructive commands.',
        '3. Do NOT use ExitPlanMode or any native planning tools — output the plan directly.',
        '4. Read files, search code, and explore — but do not change source code.',
        '5. After outputting your plan, write it to `.context/plan.md` (`mkdir -p .context` first).',
        '',
        '## Workspace Lifecycle',
        '',
        'You are in the plan phase — the **principal engineer** designing the approach:',
        '',
        '1. Discovery (done) — The PM explored the codebase and produced a findings brief.',
        '   If `.context/discovery.md` exists, read it — that is your input.',
        '',
        '2. Plan (you are here) — Read code, analyze, and produce a structured architectural plan.',
        '   The user reviews your plan in the Flux UI before proceeding.',
        '',
        '3. Build — Once approved, a **senior software engineer** implements the plan',
        '   step-by-step in this same workspace branch.',
        '',
        'Your plan output is parsed by Flux to seed the progress tracker for the build phase.',
        'The numbered steps in your "### Steps" section become the todo items the implementing',
        'engineer will work through. Keep step titles short and action-oriented.',
        '',
        ...buildOutcomeSection(ctx),
      );
    }

    lines.push('', '</flux-skill>');
    return lines.join('\n');
  },
};

// ---------------------------------------------------------------------------
// Outcome section — instructs agents to use .context/state.json
// ---------------------------------------------------------------------------

function buildOutcomeSection(ctx: SkillContext, opts?: { fromReview?: boolean }): string[] {
  const ws = ctx.workspace!;
  const lines = [
    '## Outcome Signals',
    '',
    `Your workspace is currently in the \`${ws.outcome}\` outcome state.`,
    'You are responsible for transitioning the workspace to the correct outcome when your work warrants it.',
    '',
    'Set the `outcome` and `workspace_name` fields in `.context/state.json`:',
    '',
    '```json',
    '{ "outcome": "<target_outcome>", "workspace_name": "Short Description" }',
    '```',
    '',
    'Valid outcomes: `in_progress`, `planned`, `ready_for_pr`',
    '',
    'Guidelines:',
    '- `ready_for_pr` — Your changes are complete and ready for the user to review and commit.',
    '- `planned` — You produced a plan (plan mode only).',
    '- `in_progress` — Work is ongoing, not yet at a reviewable state.',
    '',
    'Rules:',
    '- workspace_name: A 3-5 word description of what was done (displayed as the workspace title — does NOT rename directories or branches).',
    '- Write the file once at the end of your work (or update it alongside todo progress).',
  ];

  if (ctx.mode === 'plan') {
    lines.push(
      '',
      'Since you are in plan mode, set `outcome` to `planned` when your plan is complete:',
      '',
      '```json',
      '{ "outcome": "planned", "workspace_name": "Plan: Fix Token Refresh" }',
      '```',
    );
  } else if (ctx.mode === 'discovery') {
    lines.push(
      '',
      'Since you are in discovery mode, set `outcome` to `in_progress` when your findings are complete:',
      '',
      '```json',
      '{ "outcome": "in_progress", "workspace_name": "Explore Token Refresh Flow" }',
      '```',
    );
  } else if (opts?.fromReview) {
    lines.push(
      '',
      'When you start making changes based on review feedback, **immediately** set `outcome` to `in_progress`:',
      '',
      '```json',
      '{ "outcome": "in_progress", "workspace_name": "Fix Token Refresh Logic" }',
      '```',
      '',
      'When all requested changes are complete and ready for re-review, set `outcome` to `ready_for_pr`:',
      '',
      '```json',
      '{ "outcome": "ready_for_pr", "workspace_name": "Fix Token Refresh Logic" }',
      '```',
    );
  } else {
    lines.push(
      '',
      'When all work is finished and ready for review, set `outcome` to `ready_for_pr`:',
      '',
      '```json',
      '{ "outcome": "ready_for_pr", "workspace_name": "Fix Token Refresh Logic" }',
      '```',
    );
  }

  return lines;
}
