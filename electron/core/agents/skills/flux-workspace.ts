import type { FluxSkill, SkillContext } from './types';

const TERMINAL_OUTCOMES = new Set(['merged', 'ready_to_merge', 'ready_to_archive']);
const PLAN_APPROVED_OUTCOMES = new Set(['planned']);
const REVIEW_OUTCOMES = new Set(['reviewing', 'changes_requested']);

/**
 * Flux Workspace skill — loaded for non-merge tasks running in a workspace.
 *
 * The agent is the authority on outcome transitions. It emits outcome signals
 * to tell Flux when the workspace state should change. Flux only overrides
 * this for external events (sync detecting a merge, unarchive, merge actions).
 */
export const fluxWorkspaceSkill: FluxSkill = {
  id: 'flux-workspace',
  name: 'Flux Workspace',

  isRelevant(ctx: SkillContext): boolean {
    return !!ctx.workspace && ctx.workspaceAction !== 'merge';
  },

  buildPrompt(ctx: SkillContext): string {
    const ws = ctx.workspace!;

    const contextTable = [
      '| Property | Value |',
      '|----------|-------|',
      `| Branch | \`${ws.branch}\` |`,
      `| Working directory | \`${ws.worktreePath}\` |`,
      `| Parent repository | \`${ws.parentRepo}\` |`,
      `| Current outcome | \`${ws.outcome}\` |`,
    ].join('\n');

    // ── Plan approved: ready for implementation ──
    if (PLAN_APPROVED_OUTCOMES.has(ws.outcome) && ctx.mode === 'act') {
      return [
        '<flux-skill name="workspace" mode="implementing-plan">',
        '',
        '## Workspace Context',
        'A plan has been approved for this workspace. Implement the approved plan.',
        '',
        contextTable,
        '',
        'Follow the plan steps. Commit changes with clear messages when done.',
        'Review `.context/plan.md` for the approved plan.',
        'Do NOT push to remote or create pull requests.',
        '',
        ...buildOutcomeSection(ctx),
        '',
        '</flux-skill>',
      ].join('\n');
    }

    // ── Review in progress or changes requested ──
    if (REVIEW_OUTCOMES.has(ws.outcome)) {
      const isChangesRequested = ws.outcome === 'changes_requested';
      return [
        `<flux-skill name="workspace" mode="${isChangesRequested ? 'changes-requested' : 'reviewing'}">`,
        '',
        '## Workspace Context',
        isChangesRequested
          ? 'The reviewer has requested changes on this workspace. Address the feedback.'
          : 'This workspace is currently under review.',
        '',
        contextTable,
        '',
        isChangesRequested
          ? 'Make only the requested changes. Commit with clear messages when done.'
          : 'Only make changes if the reviewer asks for them.',
        'Do NOT push to remote or create pull requests.',
        '',
        ...buildOutcomeSection(ctx),
        '',
        '</flux-skill>',
      ].join('\n');
    }

    // ── Terminal workspace: minimal context, no re-work ──
    if (TERMINAL_OUTCOMES.has(ws.outcome)) {
      return [
        '<flux-skill name="workspace" mode="completed">',
        '',
        '## Workspace Context',
        `This workspace has already been completed (outcome: **${ws.outcome}**).`,
        '',
        contextTable,
        '',
        '**Do NOT repeat or redo previous work.** Only respond to the user\'s new message.',
        'If they want additional changes, make only those specific changes.',
        '',
        '</flux-skill>',
      ].join('\n');
    }

    const lines = [`<flux-skill name="workspace" mode="${ctx.mode}">`];

    if (ctx.mode === 'act') {
      // ── Early branch naming guidance (skip on resumed sessions) ──
      if (ctx.isAutoGeneratedBranch && !ctx.isExistingSession) {
        lines.push(
          '',
          '## Branch Naming',
          '',
          'The current branch/worktree name is auto-generated.',
          'Before doing any other work, analyze the user prompt and derive a concise',
          'descriptive branch name (3-5 words, lowercase, hyphen-separated).',
          'Prefer intent-aware naming over copying the first few prompt words.',
          '',
          'First action (run this before continuing):',
          '',
          '`git branch -m <descriptive-name>`',
          '',
          'After renaming, continue implementation in this renamed branch/worktree.',
          '',
          'Include a human-friendly version of the same title as `workspace_name` in your',
          'final FLUX_SIGNAL outcome line so Flux can keep workspace metadata in sync.',
          '',
          'Good examples: `fix-token-refresh-logic`, `improve-workspace-rename-ux`.',
        );
      }

      lines.push(
        '',
        '## Workspace Context',
        'You are working in an isolated workspace branch managed by Flux.',
        '',
        contextTable,
      );

      // ── Work rules ──
      lines.push(
        '',
        '## Work Rules',
        '',
        '1. Make changes directly in the workspace.',
        '2. Commit with clear, descriptive messages when done.',
        '3. Do NOT push to remote or create pull requests — the user merges via the Flux UI.',
        '4. After committing, summarize what you changed.',
        '5. If `.context/attachments.json` exists, review it for any persisted image or file attachment context.',
      );

      if (ctx.hasNativeTodoTool) {
        lines.push(
          '',
          '## Progress Tracking',
          '',
          'Use your native TodoWrite tool to track progress. Write all planned steps as todo items,',
          'then mark each as completed as you finish it. Do NOT write inline step markers like',
          '"Step 1:", "Step 2:" in your response text — use TodoWrite instead.',
        );
      }

      // ── Outcome signals ──
      lines.push('', ...buildOutcomeSection(ctx));
    } else if (ctx.mode === 'plan') {
      lines.push(
        '',
        '## Workspace Context',
        'You are working in an isolated workspace branch managed by Flux.',
        '',
        contextTable,
        '',
        '## Work Rules',
        '',
        '1. Analyze the codebase and create a detailed plan.',
        '2. Do NOT modify source files or run destructive commands.',
        '3. Do NOT use ExitPlanMode or any native planning tools — output the plan directly.',
        '4. Read files, search code, and explore — but do not change source code.',
        '5. After outputting your plan, write it to `.context/plan.md` (`mkdir -p .context` first).',
        '',
        '## Workspace Lifecycle',
        '',
        'You are in the plan phase of a two-phase workflow:',
        '',
        '1. Plan (you are here) — Read code, analyze, and produce a structured plan.',
        '   The user reviews your plan in the Flux UI before proceeding.',
        '',
        '2. Act — Once the user approves, a separate agent implements the plan',
        '   step-by-step in this same workspace branch.',
        '',
        'Your plan output is parsed by Flux to seed the progress tracker for the act phase.',
        'The numbered steps in your "### Steps" section become the todo items the implementing',
        'agent will work through. Keep step titles short and action-oriented.',
        '',
        ...buildOutcomeSection(ctx),
      );
    }

    lines.push('', '</flux-skill>');
    return lines.join('\n');
  },
};

// ---------------------------------------------------------------------------
// Outcome signal instructions
// ---------------------------------------------------------------------------

function buildOutcomeSection(ctx: SkillContext): string[] {
  const ws = ctx.workspace!;
  const lines = [
    '## Outcome Signals',
    '',
    `Your workspace is currently in the \`${ws.outcome}\` outcome state.`,
    'You are responsible for transitioning the workspace to the correct outcome when your work warrants it.',
    '',
    'Emit an outcome signal on its own line (NOT inside a code block):',
    '',
    'FLUX_SIGNAL: {"type":"outcome","outcome":"<target_outcome>","workspace_name":"Short Description"}',
    '',
    'Valid outcomes: `in_progress`, `planned`, `ready_for_pr`',
    '',
    'Guidelines:',
    '- `ready_for_pr` — You have committed meaningful changes and the work is complete or at a review-ready checkpoint.',
    '- `planned` — You produced a plan (plan mode only).',
    '- `in_progress` — Work is ongoing, not yet at a reviewable state.',
    '',
    'Rules:',
    '- workspace_name: A 3-5 word description of what was done (used as the workspace title).',
    '- Emit exactly once, as the very last line of your final response.',
    '- This line must NOT be inside a code block.',
  ];

  // Suggest the most likely target outcome based on mode
  if (ctx.mode === 'plan') {
    lines.push(
      '',
      'Since you are in plan mode, emit `planned` when your plan is complete:',
      '',
      'FLUX_SIGNAL: {"type":"outcome","outcome":"planned","workspace_name":"Plan: Fix Token Refresh"}',
    );
  } else {
    lines.push(
      '',
      'When all work is finished and committed, emit `ready_for_pr`:',
      '',
      'FLUX_SIGNAL: {"type":"outcome","outcome":"ready_for_pr","workspace_name":"Fix Token Refresh Logic"}',
    );
  }

  return lines;
}
