import type { AgentId, TaskMode } from '../types';
import type { FluxSkill, SkillContext } from './types';
import { fluxAttachmentsSkill } from './flux-attachments';
import { fluxMergeSkill } from './flux-merge';
import { fluxWorkspaceSkill } from './flux-workspace';
import { fluxPlanSkill } from './flux-plan';
import { fluxAskSkill } from './flux-ask';
import { fluxArchitectSkill } from './flux-architect';
import { fluxTodoSkill } from './flux-todo';

export type { FluxSkill, SkillContext } from './types';
export type { FluxSignal, FluxSignalType } from './types';

// ---------------------------------------------------------------------------
// Skill registry — add new skills here
// ---------------------------------------------------------------------------

const ALL_SKILLS: FluxSkill[] = [
  fluxWorkspaceSkill,
  fluxMergeSkill,
  fluxPlanSkill,
  fluxAskSkill,
  fluxArchitectSkill,
  fluxTodoSkill,
  fluxAttachmentsSkill,
];

// Agents that have their own native todo/task tracking tool
const AGENTS_WITH_NATIVE_TODO = new Set<AgentId>(['claude-code']);

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export interface ComposeSkillsOptions {
  agentId: AgentId;
  mode: TaskMode;
  isExistingSession: boolean;
  workspaceAction?: 'merge';
  merge?: {
    targetBranch: string;
    squash: boolean;
  };
  workspace?: {
    branch: string;
    worktreePath: string;
    parentRepo: string;
    outcome: string;
  };
  attachments?: {
    manifestPath: string;
    imageCount: number;
    fileCount: number;
  };
  isAutoGeneratedBranch: boolean;
}

/**
 * Compose all relevant skill prompts for the given context.
 * Returns null if no skills are relevant.
 *
 * Skills are wrapped in <flux-skill> tags for clear boundary markers.
 * The workspace state protocol (FLUX_WORKSPACE) is injected for lifecycle
 * transitions. The FLUX_SIGNAL protocol in the todo skill handles progress
 * tracking for agents without native tools.
 */
export function composeSkillPrompts(options: ComposeSkillsOptions): string | null {
  const ctx: SkillContext = {
    agentId: options.agentId,
    mode: options.mode,
    workspaceAction: options.workspaceAction,
    isExistingSession: options.isExistingSession,
    hasNativeTodoTool: AGENTS_WITH_NATIVE_TODO.has(options.agentId),
    isAutoGeneratedBranch: options.isAutoGeneratedBranch,
    merge: options.merge,
    workspace: options.workspace,
    attachments: options.attachments,
  };

  const sections: string[] = [];

  for (const skill of ALL_SKILLS) {
    if (skill.isRelevant(ctx)) {
      sections.push(skill.buildPrompt(ctx));
    }
  }

  // Note: the fluxWorkspaceSkill already handles completion signals via FLUX_SIGNAL.
  // The legacy FLUX_WORKSPACE_LIFECYCLE protocol is no longer injected to avoid
  // duplicate lifecycle messages in the UI.

  if (sections.length === 0) return null;
  return sections.join('\n\n');
}

/**
 * Get a list of skill IDs that are active for the given context.
 * Useful for diagnostics/logging.
 */
export function getActiveSkillIds(options: ComposeSkillsOptions): string[] {
  const ctx: SkillContext = {
    agentId: options.agentId,
    mode: options.mode,
    workspaceAction: options.workspaceAction,
    isExistingSession: options.isExistingSession,
    hasNativeTodoTool: AGENTS_WITH_NATIVE_TODO.has(options.agentId),
    isAutoGeneratedBranch: options.isAutoGeneratedBranch,
    merge: options.merge,
    workspace: options.workspace,
    attachments: options.attachments,
  };

  return ALL_SKILLS.filter((s) => s.isRelevant(ctx)).map((s) => s.id);
}
