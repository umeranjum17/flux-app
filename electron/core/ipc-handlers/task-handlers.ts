const execFileAsync = promisify(execFile);

const MAX_RECOVERY_DELAY_MS = 5000;

function recoveryDelay(retryCount: number): number {
  return Math.min(RECOVERY_DELAY_MS * Math.pow(2, retryCount), MAX_RECOVERY_DELAY_MS);
}

export function registerTaskHandlers(ctx: BaseIpcContext): {
  spawnTaskRun: (options: SpawnTaskRunOptions) => Promise<{ taskId: string; session: any }>;
  releaseTask: (taskId: string) => void;
} {
  const {
    mainWindow,
    sessionStore,
    configManager,
    usageTracker,
    workspaceStore,
    sendToRenderer,
    lifecycleManager,
    activeTasks,
    taskSessions,
    cleaningUp,
    taskIdleHeartbeats,
    taskStallMonitors,
    taskRetryCounts,
    activeSubagents,
    cachedRateLimits,
    getCurrentCwd,
    getLocalCwd,
    getSshHost,
  } = ctx;

  // Circuit breaker: track crash timestamps per workspace to prevent
  // infinite crash loops from workspace-specific issues (corrupt git, disk full)
  const CIRCUIT_BREAKER_MAX_CRASHES = 5;
  const CIRCUIT_BREAKER_WINDOW_MS = 10 * 60 * 1000; // 10 minutes
  const workspaceCrashTimestamps = new Map<string, number[]>();

  const isCircuitBreakerOpen = (workspaceId: string): boolean => {
    const timestamps = workspaceCrashTimestamps.get(workspaceId);
    if (!timestamps) return false;
    const now = Date.now();
    const recent = timestamps.filter(t => now - t < CIRCUIT_BREAKER_WINDOW_MS);
    workspaceCrashTimestamps.set(workspaceId, recent);
    return recent.length >= CIRCUIT_BREAKER_MAX_CRASHES;
  };

  const recordWorkspaceCrash = (workspaceId: string): void => {
    const timestamps = workspaceCrashTimestamps.get(workspaceId) ?? [];
    timestamps.push(Date.now());
    workspaceCrashTimestamps.set(workspaceId, timestamps);
  };

  const resolveQualityGateCommands = async (_cwd: string): Promise<string[]> => {
    return configManager.get().qualityGateCommands
      .map((command: string) => command.trim())
      .filter(Boolean);
  };

  const emitQualityGateMessage = (taskId: string, sessionId: string, message: AgentMessage) => {
    sessionStore.addMessage(sessionId, toStoredMessage(message));
    sendToRenderer('agent:message', { taskId, message });
  };

  const emitTaskMessage = (taskId: string, sessionId: string, message: AgentMessage) => {
    sessionStore.addMessage(sessionId, toStoredMessage(message));
    sendToRenderer('agent:message', { taskId, message });
  };

  const emitSubagentMessage = (
    parentTaskId: string,
    subagentId: string,
    subagentName: string,
    message: AgentMessage,
  ) => {
    const payload: AgentMessage = {
      ...message,
      subagentId,
      subagentName,
      ...(message.subagentStatus ? {} : { subagentStatus: 'running' }),
    };
    sendToRenderer('agent:message', { taskId: parentTaskId, message: payload });
  };

  const persistAgentSessionId = (sessionId: string, agentId: AgentId, agentSessionId: string) => {
    const current = sessionStore.get(sessionId);
    if (!current) return;

    const baseMetadata = current.metadata ?? {};
    const currentAgentSessions = isRecord(baseMetadata.agentSessions)
      ? baseMetadata.agentSessions
      : {};
    const metadata = {
      ...baseMetadata,
      agentSessions: {
        ...currentAgentSessions,
        [agentId]: {
          sessionId: agentSessionId,
        },
      },
    };

    sessionStore.update(sessionId, { metadata });
  };

  const recordWorkspaceCheckpoint = async (workspaceId: string, prompt: string, sessionId: string) => {
    const workspace = workspaceStore.get(workspaceId);
    if (!workspace) return;

    const checkpoint = await createCheckpoint(
      workspace.worktreePath,
      workspaceId,
      sessionId,
      listCheckpoints(workspaceId).length + 1,
      buildSessionTitle(prompt),
    );
    sendToRenderer('workspace:checkpoint', { workspaceId, checkpoint });
  };

  // -----------------------------------------------------------------------
  // Canonical task cleanup — ONE function that ALL paths use
  // -----------------------------------------------------------------------

  /**
   * Stop agent process + subagents, clear all timers, remove from shared
   * state maps. Does NOT touch lifecycle manager state (callers do that).
   * Idempotent: safe to call multiple times for the same taskId.
   */
  const releaseTask = (taskId: string): void => {
    // Stop subagents first
    for (const [subId, sub] of activeSubagents.entries()) {
      if (sub.parentTaskId !== taskId) continue;
      sub.handle.stop();
      sub.handle.removeAllListeners();
      activeSubagents.delete(subId);
      activeTasks.delete(subId);
      taskSessions.delete(subId);
    }

    // Stop main agent
    const handle = activeTasks.get(taskId);
    if (handle) {
      handle.removeAllListeners();
      void handle.stop();
    }
    activeTasks.delete(taskId);
    untrackAgentPid(taskId);

    // Clear timers
    if (taskIdleHeartbeats.has(taskId)) {
      clearInterval(taskIdleHeartbeats.get(taskId)!);
      taskIdleHeartbeats.delete(taskId);
    }
    taskStallMonitors.get(taskId)?.dispose();
    taskStallMonitors.delete(taskId);
    taskRetryCounts.delete(taskId);
    taskSessions.delete(taskId);
    cleaningUp.delete(taskId);
  };

  /** Clean up a task's resources without emitting agent:done (used by stall monitor). */
  const cleanupTask = (taskId: string) => {
    releaseTask(taskId);
    // Release with 'error' so the workspace status transitions correctly
    // instead of silently staying stuck as 'running'.
    lifecycleManager.taskReleasedWithStatus(taskId, 'error');
  };

  /** Stop the current agent and respawn with conversation context. */
  const triggerAutoRecovery = async (
    taskId: string,
    sessionId: string,
    agentId: AgentId,
    originalOptions: SpawnTaskRunOptions,
  ) => {
    // Circuit breaker: too many crashes in this workspace
    const wsIdForRecovery = originalOptions.workspaceId;
    if (wsIdForRecovery) {
      recordWorkspaceCrash(wsIdForRecovery);
      if (isCircuitBreakerOpen(wsIdForRecovery)) {
        emitTaskMessage(taskId, sessionId, {
          type: 'error',
          role: 'system',
          content: `Auto-retry disabled: too many crashes in this workspace. Please investigate the underlying issue.`,
          timestamp: Date.now(),
        });
        return;
      }
    }

    const retryCount = taskRetryCounts.get(taskId) ?? 0;
    taskRetryCounts.set(taskId, retryCount + 1);

    const monitor = taskStallMonitors.get(taskId);
    if (monitor) {
      monitor.recordRestart();
      monitor.dispose();
    }

    emitTaskMessage(taskId, sessionId, {
      type: 'status',
      role: 'system',
      statusKind: 'progress',
      content: `Auto-recovering stalled session (attempt ${retryCount + 1}/${MAX_AUTO_RETRIES})...`,
      timestamp: Date.now(),
    });

    // Use releaseTask for cleanup but preserve lifecycle state
    // (the task is being restarted, not truly released)
    const handle = activeTasks.get(taskId);
    if (handle) {
      await handle.stop();
      handle.removeAllListeners();
    }
    activeTasks.delete(taskId);
    taskSessions.delete(taskId);
    if (taskIdleHeartbeats.has(taskId)) {
      clearInterval(taskIdleHeartbeats.get(taskId)!);
      taskIdleHeartbeats.delete(taskId);
    }

    await new Promise(resolve => setTimeout(resolve, recoveryDelay(retryCount)));

    // Guard: if workspace:stop cleaned up while we awaited, bail
    if (!lifecycleManager.isTaskActive(taskId)) return;

    try {
      const context = buildConversationContext(sessionId, sessionStore);
      await spawnTaskRun({
        ...originalOptions,
        sessionId,
        fallbackContext: context || undefined,
        prompt: '[Resuming previous session]',
      });
    } catch (err) {
      sendToRenderer('agent:done', {
        taskId,
        error: `Recovery failed: ${err instanceof Error ? err.message : String(err)}`,
      });
      releaseTask(taskId);
      lifecycleManager.taskReleasedWithStatus(taskId, 'error');
    }
  };

  const spawnTaskRun = async (
    options: SpawnTaskRunOptions,
  ): Promise<{ taskId: string; session: any }> => {
    requireFields(options as unknown as Record<string, unknown>, 'taskId', 'prompt', 'cwd');
    const agentId = (options.agentId ?? 'claude-code') as AgentId;
    const sshHost = getSshHost();
    const localCwd = getLocalCwd();
    const workspace = options.workspaceId
      ? workspaceStore.get(options.workspaceId)
      : workspaceStore.get(options.taskId);
    if (activeTasks.has(options.taskId)) {
      // Capture before releaseTask removes it from the map
      const priorHandle = activeTasks.get(options.taskId);
      releaseTask(options.taskId);
      lifecycleManager.clearTask(options.taskId);
      // Await old process death so the session lock is released before respawning.
      // This prevents "session already in use" conflicts when the user switches
      // model mid-execution, which would otherwise cause spurious spawn failures.
      if (priorHandle) {
        await priorHandle.stop().catch(() => {});
      }
    }

    let effectivePrompt = await buildPromptWithAttachments(options.prompt, options.attachments, sshHost);

    const repoMapConfig = configManager.get().repoMap;
    if (repoMapConfig.enabled && repoMapConfig.perAgentEnabled[agentId] !== false) {
      try {
        const repoMap = await repoMapService.getMap(effectivePrompt, repoMapConfig.maxTokens);
        if (repoMap) {
          options.contextBlock = repoMap;
          effectivePrompt = repoMap + '\n\n' + effectivePrompt;
        }
      } catch {
        // Repo map generation failed — continue without it
      }
    }

    const existingSession = options.sessionId ? sessionStore.get(options.sessionId) : null;
    const session = existingSession ?? sessionStore.create({
      title: workspace ? `[WS] ${workspace.name}` : buildSessionTitle(options.prompt),
      agentId,
      model: options.model ?? '',
      mode: options.mode,
      cwd: options.cwd,
      metadata: workspace ? { workspaceId: workspace.id } : {},
    });
    const startedAt = Date.now();
    const existingAgentSessionId = readAgentSessionId(existingSession?.metadata, agentId);
    const spawnCwd = sshHost ? localCwd : options.cwd;

    const claudeResumeId = sshHost
      ? existingAgentSessionId
      : session.id;

    const fallbackContext = existingSession
      ? buildConversationContext(session.id, sessionStore)
      : undefined;

    if (workspace && options.workspaceAction !== 'merge') {
      const wsContext = buildWorkspaceSystemContext(workspace, options.mode, options.workspaceAction, agentId, !!existingSession);
      if (wsContext) {
        effectivePrompt = `${wsContext}\n\n${effectivePrompt}`;
      }

      // Notify renderer which skills are active
      const skillIds = getActiveSkillIds({
        agentId,
        mode: options.mode,
        isExistingSession: !!existingSession,
        isAutoGeneratedBranch: isAutoGeneratedBranch(workspace.branch),
        workspace: {
          branch: workspace.branch,
          worktreePath: workspace.worktreePath,
          parentRepo: workspace.parentRepo,
          outcome: workspace.outcome,
        },
      });
      if (skillIds.length > 0) {
        const SKILL_META: Record<string, { name: string; description: string }> = {
          'flux-workspace': { name: 'Flux Workspace', description: 'Branch management, commits, and completion signals' },
          'flux-plan': { name: 'Flux Plan', description: 'Structured planning with progress tracking' },
          'flux-todo': { name: 'Flux Todo', description: 'Step-by-step task tracking and progress signals' },
        };
        sendToRenderer('agent:skills', {
          taskId: options.taskId,
          skills: skillIds.map((id) => ({
            id,
            name: SKILL_META[id]?.name ?? id,
            description: SKILL_META[id]?.description ?? '',
          })),
        });
      }
    }

    const spawnOptions: SpawnOptions = {
      ...options,
      cwd: spawnCwd,
      remoteCwd: sshHost ? options.cwd : undefined,
      sshHost: sshHost ?? undefined,
      dangerouslyBypassPermissions: (agentId === 'claude-code' && options.mode !== 'plan')
        || (agentId === 'codex' && options.mode === 'act')
        || (agentId === 'copilot' && options.mode === 'act')
        || options.workspaceAction === 'merge',
      prompt: effectivePrompt,
      sessionId: agentId === 'claude-code' ? session.id : options.sessionId,
      resumeSessionId: agentId === 'codex'
        ? existingAgentSessionId
        : agentId === 'copilot'
          ? (existingAgentSessionId ?? session.id)
          : agentId === 'claude-code'
            ? claudeResumeId
            : undefined,
      fallbackContext: fallbackContext || undefined,
    };
    let detectedCodexSessionId: string | undefined = existingAgentSessionId;

    if (sshHost) {
      try {
        await execFileAsync(
          resolveSshCommand(),
          ['-o', 'ConnectTimeout=3', '-o', 'BatchMode=yes', sshHost, 'echo', 'ok'],
          { timeout: 5000, env: extendedEnv() },
        );
      } catch (err: any) {
        const info = classifySpawnError(err as Error, { command: 'ssh', sshHost });
        if (!existingSession) {
          sessionStore.delete(session.id);
        }
        throw new Error(`SSH connection failed: ${info.userMessage}${info.suggestion ? `. ${info.suggestion}` : ''}`);
      }
    }

    const resumeMessages = (agentId === 'openai' && existingSession)
      ? sessionStore.getMessages(session.id)
      : undefined;

    let pendingTodoItems: Array<{ id: number; label: string; status: 'pending' | 'in_progress' | 'done' }> | null = null;

    const isAgentSwitch = existingSession && existingSession.agentId !== agentId;
    if (isAgentSwitch) {
      const fromAgent = getAgentLabel(existingSession.agentId as AgentId);
      if (existingSession.mode === 'plan' && options.mode === 'act') {
        const planText = extractFullPlanText(sessionStore, session.id);
        const planPath = await writePlanFile(options.cwd, planText);
        const planSteps = extractPlanTodoItems(sessionStore, session.id);
        const stepTracking = buildStepTrackingPrompt(planSteps, agentId);
        spawnOptions.prompt = [
          `You are implementing a plan created by ${fromAgent}. The approved plan is below.`,
          planPath ? `The full plan is also saved at \`${planPath}\`.` : '',
          '',
          planText ? `## Approved Plan\n\n${planText}` : '',
          stepTracking,
          '',
          `## User instruction`,
          spawnOptions.prompt,
        ].filter(Boolean).join('\n');

        if (planSteps.length > 0) {
          pendingTodoItems = planSteps.map((s, i) => ({ id: i + 1, label: s.label, status: 'pending' as const }));
        }
      } else {
        const context = buildConversationContext(session.id, sessionStore);
        if (context) {
          spawnOptions.prompt = [
            `You are continuing a conversation previously handled by ${fromAgent}. Here is the context:`,
            '',
            context,
            '',
            `## Current request`,
            spawnOptions.prompt,
          ].join('\n');
        }
      }
    }

    const hasWorkingResume = AGENTS_WITH_NATIVE_RESUME.has(agentId) && !!spawnOptions.resumeSessionId;
    if (existingSession && !isAgentSwitch && !hasWorkingResume) {
      const isPlanToAct = existingSession.mode === 'plan' && options.mode === 'act';
      if (isPlanToAct) {
        const planText = extractFullPlanText(sessionStore, session.id);
        const planPath = await writePlanFile(options.cwd, planText);
        const planSteps = extractPlanTodoItems(sessionStore, session.id);
        const stepTracking = buildStepTrackingPrompt(planSteps, agentId);
        spawnOptions.prompt = [
          'You are implementing an approved plan. The full plan is below.',
          planPath ? `The plan is also saved at \`${planPath}\`.` : '',
          '',
          planText ? `## Approved Plan\n\n${planText}` : '',
          stepTracking,
          '',
          `## Current request`,
          spawnOptions.prompt,
        ].filter(Boolean).join('\n');

        if (planSteps.length > 0) {
          pendingTodoItems = planSteps.map((s, i) => ({ id: i + 1, label: s.label, status: 'pending' as const }));
        }
      } else {
        const context = buildConversationContext(session.id, sessionStore);
        if (context) {
          spawnOptions.prompt = [
            `You are continuing a previous conversation. Here is the context:`,
            '',
            context,
            '',
            `## Current request`,
            spawnOptions.prompt,
          ].join('\n');
        }
      }
    }

    if (existingSession && !isAgentSwitch && existingSession.mode === 'plan' && options.mode === 'act' && hasWorkingResume) {
      const planText = extractFullPlanText(sessionStore, session.id);
      const planPath = await writePlanFile(options.cwd, planText);
      const planSteps = extractPlanTodoItems(sessionStore, session.id);
      const stepTracking = buildStepTrackingPrompt(planSteps, agentId);
      spawnOptions.prompt = [
        'The user reviewed and approved the plan above. Implement each step now.',
        planPath ? `The full plan is also saved at \`${planPath}\`.` : '',
        stepTracking,
        '',
        spawnOptions.prompt,
      ].filter(Boolean).join('\n');

      if (planSteps.length > 0) {
        pendingTodoItems = planSteps.map((s, i) => ({ id: i + 1, label: s.label, status: 'pending' as const }));
      }
    }

    if (existingSession && !isAgentSwitch && AGENTS_WITH_NATIVE_RESUME.has(agentId) && !spawnOptions.resumeSessionId) {
      emitTaskMessage(options.taskId, session.id, {
        type: 'status',
        role: 'system',
        statusKind: 'progress',
        content: 'Continuing with conversation context (session resume unavailable)',
        timestamp: Date.now(),
      });
    }

    const preRunRef = await captureGitSnapshot(options.cwd);

    const qualityGateBaseline = new Map<string, boolean>();
    if (options.mode === 'act' && !sshHost) {
      const baselineCommands = await resolveQualityGateCommands(options.cwd);
      for (const cmd of baselineCommands) {
        const baseResult = await runShellCommand(cmd, options.cwd, sshHost);
        qualityGateBaseline.set(cmd, baseResult.exitCode === 0);
      }
    }

    let handle: AgentHandle;
    try {
      handle = agentManager.spawn(agentId, spawnOptions, resumeMessages);
    } catch (err) {
      if (!existingSession) {
        sessionStore.delete(session.id);
      }
      throw err;
    }

    if (existingSession) {
      sessionStore.update(session.id, {
        agentId,
        model: options.model ?? session.model,
        mode: options.mode,
        cwd: options.cwd,
        metadata: workspace ? { ...(session.metadata ?? {}), workspaceId: workspace.id } : session.metadata,
      });
    }

    const initialStatus: WorkspaceStatus = options.workspaceAction === 'merge' ? 'merging' : 'running';
    if (workspace) {
      lifecycleManager.taskStarted(options.taskId, workspace.id, initialStatus, session.id);
      // Only reset terminal outcomes when the user explicitly sends a new prompt
      // (not during auto-recovery or session resume), to prevent merged/completed
      // workspaces from being accidentally restarted.
      const isExplicitUserAction = options.prompt !== '[Resuming previous session]'
        && options.workspaceAction !== 'merge';
      if (
        isExplicitUserAction
        && options.mode === 'act'
        && (workspace.outcome === 'merged' || workspace.outcome === 'ready_to_archive')
      ) {
        lifecycleManager.setOutcome(workspace.id, 'in_progress', { force: true });
      }
    }

    if (options.prompt !== '[Resuming previous session]') {
      sessionStore.addMessage(
        session.id,
        buildStoredUserMessage(options.prompt, options.images, options.attachments),
      );
    }

    activeTasks.set(options.taskId, handle);
    taskSessions.set(options.taskId, session.id);
    if (handle.pid) {
      trackAgentPid({ pid: handle.pid, taskId: options.taskId, agentId, startedAt: Date.now() });
    }
    if (workspace) {
      workspaceStore.addSession(workspace.id, session.id, options.taskId);
    }

    // Emit deferred todo items now that the task is registered in the renderer
    let todoInitialized = false;
    const pendingTodoUpdates: Array<{ stepId: number; status: 'in_progress' | 'done'; label?: string }> = [];

    const emitTodoUpdate = (taskId: string, stepId: number, status: 'in_progress' | 'done', label?: string) => {
      if (!todoInitialized) {
        pendingTodoUpdates.push({ stepId, status, label });
        return;
      }
      sendToRenderer('agent:todo-update', { taskId, stepId, status, ...(label ? { label } : {}) });
    };

    const flushTodoUpdates = (taskId: string) => {
      todoInitialized = true;
      for (const update of pendingTodoUpdates) {
        sendToRenderer('agent:todo-update', { taskId, stepId: update.stepId, status: update.status, ...(update.label ? { label: update.label } : {}) });
      }
      pendingTodoUpdates.length = 0;
    };

    if (pendingTodoItems) {
      sendToRenderer('agent:todo', { taskId: options.taskId, todoItems: pendingTodoItems });
      flushTodoUpdates(options.taskId);
    }

    const idleHeartbeat = setInterval(() => {
      if (!activeTasks.has(options.taskId) || cleaningUp.has(options.taskId)) {
        clearInterval(idleHeartbeat);
        taskIdleHeartbeats.delete(options.taskId);
        return;
      }
      sendToRenderer('agent:message', {
        taskId: options.taskId,
        message: {
          type: 'status',
          role: 'system',
          statusKind: 'progress',
          content: 'Agent is working...',
          timestamp: Date.now(),
        } satisfies AgentMessage,
      });
    }, 10_000);
    taskIdleHeartbeats.set(options.taskId, idleHeartbeat);

    taskStallMonitors.get(options.taskId)?.dispose();
    const priorRetries = taskRetryCounts.get(options.taskId) ?? 0;
    const stallMonitor = new StallMonitor({
      taskId: options.taskId,
      maxAutoRestarts: Math.max(0, MAX_AUTO_RETRIES - priorRetries),
      onStallDetected: (info) => {
        const currentStatus = lifecycleManager.getTaskStatus(options.taskId);
        if (currentStatus === 'waiting_input' || currentStatus === 'waiting_approval') {
          stallMonitor.pause();
          return;
        }

        const label = info.type === 'tool_timeout'
          ? `${info.toolName ?? 'Tool'} timed out after ${Math.round(info.durationMs / 1000)}s`
          : `No activity for ${Math.round(info.durationMs / 1000)}s`;
        emitTaskMessage(options.taskId, session.id, {
          type: 'status',
          role: 'system',
          statusKind: 'diagnostic',
          content: `Stall detected: ${label}`,
          timestamp: Date.now(),
        });
        sendToRenderer('agent:stall', {
          taskId: options.taskId,
          stallInfo: info,
        });
        if (info.autoRestartsRemaining > 0) {
          void triggerAutoRecovery(options.taskId, session.id, agentId, options);
        }
      },
      onProcessDead: () => {
        if (!cleaningUp.has(options.taskId) && activeTasks.has(options.taskId) && lifecycleManager.isTaskActive(options.taskId)) {
          emitTaskMessage(options.taskId, session.id, {
            type: 'error',
            role: 'system',
            content: 'Agent process died unexpectedly',
            timestamp: Date.now(),
          });
          sendToRenderer('agent:done', { taskId: options.taskId, error: 'Agent process died unexpectedly' });
          cleanupTask(options.taskId);
        }
      },
    });
    taskStallMonitors.set(options.taskId, stallMonitor);

    stallMonitor.startHealthCheck(() => handle.isAlive());

    emitTaskMessage(options.taskId, session.id, {
      type: 'status',
      role: 'system',
      statusKind: 'spawn',
      content: `Starting ${getAgentLabel(agentId)}...`,
      timestamp: Date.now(),
    });

    handle.on('session-meta', (meta) => {
      if (!meta || typeof meta !== 'object') return;
      const sessionMeta = meta as { id?: string };
      if (typeof sessionMeta.id !== 'string') return;
      if (agentId === 'codex') {
        detectedCodexSessionId = sessionMeta.id;
      }
      persistAgentSessionId(session.id, agentId, sessionMeta.id);
    });

    let agentUsedTodoWrite = false;
    // Accumulated text buffer for signal parsing (FLUX_WORKSPACE_LIFECYCLE, FLUX_SIGNAL,
    // FLUX_TODO, checklists). Streaming deltas split signals across multiple
    // messages, so we must parse from the accumulated buffer.
    const MAX_TODO_BUFFER = 50_000;
    let todoBuffer = '';
    let lastTodoSnapshot = '';
    let lastPlanSnapshot = '';
    const emittedStepStatuses = new Map<number, 'in_progress' | 'done'>();
    // Track already-processed lifecycle/signal events to avoid duplicates
    // when re-parsing the accumulated buffer.
    let lastLifecycleCount = 0;
    let lastFluxSignalCount = 0;
    // Deferred outcome trigger: set when the agent emits a signal during
    // streaming (before commits may exist). The actual transitionOutcome
    // call happens in the result/done handler where git state is reliable.
    let pendingOutcomeTrigger: import('../worktree/outcome').WorkspaceOutcomeTrigger | null = null;

    handle.on('agent-todo', (payload: { todos: any[] }) => {
      agentUsedTodoWrite = true;
      const todoItems = extractTodoItemsFromPayload(payload.todos ?? payload);
      sendToRenderer('agent:todo', { taskId: options.taskId, todoItems });
      flushTodoUpdates(options.taskId);
    });

    const toolHeartbeats = new Map<string, NodeJS.Timeout>();
    let resultCompletionDone = false;

    handle.on('message', (message) => {
      if (message.type === 'tool_call' && message.toolCallId) {
        if (isInteractiveToolName(message.toolName)) {
          stallMonitor.pause();
        } else {
          stallMonitor.trackToolCall(message.toolCallId, message.toolName);
        }
      } else if (message.type === 'tool_result' && message.toolCallId) {
        stallMonitor.trackToolResult(message.toolCallId);
        stallMonitor.resume();
      }
      if (message.type !== 'status' && message.type !== 'rate_limit') {
        stallMonitor.markActivity();
      }

      if (message.type === 'question_request') {
        stallMonitor.pause();
      }

      // A `result` message means the agent completed its turn.
      // With --input-format stream-json the process stays alive, so
      // handle.on('done') won't fire until the next turn ends or the
      // process is killed.  Pause stall monitoring and stop the idle
      // heartbeat so we don't falsely detect a stall and auto-restart.
      if (message.type === 'result') {
        stallMonitor.pause();
        if (taskIdleHeartbeats.has(options.taskId)) {
          clearInterval(taskIdleHeartbeats.get(options.taskId)!);
          taskIdleHeartbeats.delete(options.taskId);
        }
      }

      if (message.type === 'rate_limit') {
        logDiagnostic('usage', `rate_limit stream event from agent=${agentId}`, {
          rawRateLimitInfo: message.rateLimitInfo ? JSON.stringify(message.rateLimitInfo).slice(0, 500) : null,
        });
        const normalized = (agentId === 'claude-code' || agentId === 'codex')
          ? normalizeRateLimitInfo(
            message.rateLimitInfo as Record<string, any> | undefined,
            agentId,
          )
          : null;
        if (normalized) {
          normalized.fetchedAt = Date.now();
          const cacheKey = `${normalized.providerId}:${normalized.rateLimitType}`;
          const previous = cachedRateLimits.get(cacheKey);
          logDiagnostic('usage', `rate_limit cached: ${cacheKey}`, {
            utilization: normalized.utilization,
            status: normalized.status,
            resetsAt: normalized.resetsAt,
            rateLimitType: normalized.rateLimitType,
            previousUtilization: previous?.utilization ?? null,
            previousStatus: previous?.status ?? null,
          });
          cachedRateLimits.set(cacheKey, normalized);
        } else {
          logDiagnostic('usage', `rate_limit stream event ignored`, { agentId, reason: agentId !== 'claude-code' && agentId !== 'codex' ? 'unsupported_agent' : 'normalization_returned_null' });
        }
      }

      sessionStore.addMessage(session.id, toStoredMessage(message));

      // Accumulate text into the signal buffer for parsing FLUX_WORKSPACE_LIFECYCLE,
      // FLUX_SIGNAL, FLUX_TODO, etc. Streaming deltas split signals across
      // multiple messages, so we must parse from the accumulated buffer.
      const trackable = getStepTrackableContent(message);
      if (trackable) {
        todoBuffer += '\n' + trackable;
        if (todoBuffer.length > MAX_TODO_BUFFER) {
          todoBuffer = todoBuffer.slice(-MAX_TODO_BUFFER / 2);
          // Reset counts since we sliced the buffer — some previously counted
          // events may have been trimmed, but the remaining ones will be
          // re-parsed and de-duped on the next pass.
          lastLifecycleCount = 0;
          lastFluxSignalCount = 0;
        }

        // 1. Parse FLUX_WORKSPACE_LIFECYCLE events from accumulated buffer.
        //    Only process newly discovered events (skip already-emitted ones).
        const allWsEvents = parseAllWorkspaceEvents(todoBuffer);
        if (allWsEvents.length > lastLifecycleCount) {
          const newEvents = allWsEvents.slice(lastLifecycleCount);
          lastLifecycleCount = allWsEvents.length;

          for (const evt of newEvents) {
            const lifecycleLabels: Record<string, string> = {
              working: 'Work started',
              planned: 'Plan completed',
              ready_for_review: 'Ready for review',
              completed: 'Completed',
              merged: 'Changes merged',
            };
            if (lifecycleLabels[evt.state]) {
              const lifecycleMessage = {
                type: 'lifecycle' as const,
                role: 'system' as const,
                content: '',
                timestamp: Date.now(),
                lifecycleState: evt.state,
                lifecycleLabel: lifecycleLabels[evt.state],
              };
              sessionStore.addMessage(session.id, toStoredMessage(lifecycleMessage));
              sendToRenderer('agent:message', {
                taskId: options.taskId,
                message: lifecycleMessage,
              });
            }

            if (evt.state === 'ready_for_review' || evt.state === 'planned' || evt.state === 'merged') {
              logDiagnostic('lifecycle', `agent signalled ${evt.state}`, {
                taskId: options.taskId,
                workspaceName: evt.workspace_name,
              });

              // Defer outcome transition to result/done handler where git
              // state is reliable (agent may not have committed yet).
              if (evt.state === 'ready_for_review') {
                pendingOutcomeTrigger = 'agent_signal_ready_for_review';
              } else if (evt.state === 'planned') {
                pendingOutcomeTrigger = 'plan_completed';
              }
            }
          }
        }

        // 2. Parse FLUX_SIGNAL events from accumulated buffer.
        //    Only process newly discovered events.
        const allFluxSignals = parseAllFluxSignals(todoBuffer);
        if (allFluxSignals.length > lastFluxSignalCount) {
          const newSignals = allFluxSignals.slice(lastFluxSignalCount);
          lastFluxSignalCount = allFluxSignals.length;

          for (const sig of newSignals) {
            if (sig.type === 'step_start' && typeof sig.step === 'number') {
              if (!todoInitialized) {
                sendToRenderer('agent:todo', {
                  taskId: options.taskId,
                  todoItems: [{ id: sig.step, label: sig.label || `Step ${sig.step}`, status: 'in_progress' }],
                });
                flushTodoUpdates(options.taskId);
              }
              emitTodoUpdate(options.taskId, sig.step, 'in_progress', sig.label);
            } else if (sig.type === 'step_done' && typeof sig.step === 'number') {
              emitTodoUpdate(options.taskId, sig.step, 'done');
            } else if (sig.type === 'todo_update' && sig.todos) {
              const todoItems: NormalizedTodoItem[] = sig.todos.map((t, i) => ({
                id: i + 1,
                label: t.label,
                status: t.status,
              }));
              const snapshot = JSON.stringify(todoItems);
              if (snapshot !== lastTodoSnapshot) {
                lastTodoSnapshot = snapshot;
                sendToRenderer('agent:todo', { taskId: options.taskId, todoItems });
                flushTodoUpdates(options.taskId);
              }
            }
            // 'completed' signal → trigger workspace lifecycle transition
            else if (sig.type === 'completed') {
              logDiagnostic('flux-signal', 'agent signalled completed', {
                taskId: options.taskId,
                workspaceName: sig.workspace_name,
              });

              // Defer outcome transition to result/done handler where git
              // state is reliable (agent may not have committed yet).
              pendingOutcomeTrigger = options.mode === 'plan' ? 'plan_completed' : 'agent_signal_ready_for_review';

              // Emit a lifecycle message to the renderer
              const lifecycleMessage = {
                type: 'lifecycle' as const,
                role: 'system' as const,
                content: '',
                timestamp: Date.now(),
                lifecycleState: options.mode === 'plan' ? 'planned' : 'ready_for_review',
                lifecycleLabel: options.mode === 'plan' ? 'Plan completed' : 'Ready for review',
              };
              sessionStore.addMessage(session.id, toStoredMessage(lifecycleMessage));
              sendToRenderer('agent:message', {
                taskId: options.taskId,
                message: lifecycleMessage,
              });
            }
          }
        }
      }

      // Fallback: FLUX_TODO JSON, todo blocks, checklists, step markers
      // (covers Codex/Copilot that can't use TodoWrite).
      // Skip when Claude CLI's native TodoWrite is active — it provides its own
      // structured updates and these fallback parsers are not relevant for it.
      if (!agentUsedTodoWrite && trackable) {
        // Strip FLUX_WORKSPACE / legacy FLUX_WORKSPACE_LIFECYCLE lines before feeding
        // into todo parsers — these are workspace state, not progress items.
        const todoOnlyBuffer = todoBuffer
          .split('\n')
          .filter(line => !line.match(/^FLUX_(?:WORKSPACE_LIFECYCLE|WORKSPACE|LIFECYCLE):\s*\{/))
          .join('\n');

        const progress = parseAgentTodos(todoOnlyBuffer);

        if (progress.source === 'flux_todo' || progress.source === 'todo_block' || progress.source === 'checklist') {
          const snapshot = JSON.stringify(progress.items);
          if (snapshot !== lastTodoSnapshot) {
            lastTodoSnapshot = snapshot;
            sendToRenderer('agent:todo', { taskId: options.taskId, todoItems: progress.items });
            flushTodoUpdates(options.taskId);
          }
        } else if (progress.source === 'step_markers') {
          const { markers } = progress;
          if (markers.length > 0 && !todoInitialized) {
            const labelMap = new Map(markers.filter((m) => m.label).map((m) => [m.stepId, m.label!]));
            const doneIds = new Set(markers.filter((m) => m.status === 'done').map((m) => m.stepId));
            const startIds = new Set(markers.filter((m) => m.status === 'in_progress').map((m) => m.stepId));
            const maxStep = Math.max(...markers.map((m) => m.stepId));
            const seeded: NormalizedTodoItem[] = [];
            for (let step = 1; step <= maxStep; step++) {
              seeded.push({
                id: step,
                label: labelMap.get(step) || `Step ${step}`,
                status: doneIds.has(step) ? 'done' : startIds.has(step) ? 'in_progress' : 'pending',
              });
            }
            sendToRenderer('agent:todo', { taskId: options.taskId, todoItems: seeded });
            flushTodoUpdates(options.taskId);
          }
          for (const marker of markers) {
            const prevStatus = emittedStepStatuses.get(marker.stepId);
            if (prevStatus === marker.status) continue;
            emittedStepStatuses.set(marker.stepId, marker.status);
            emitTodoUpdate(options.taskId, marker.stepId, marker.status, marker.label);
          }
        }
      }

      // Parse FLUX_PLAN: structured plan data from agent output
      if (options.mode === 'plan' && trackable && trackable.includes('FLUX_PLAN:')) {
        const planData = parseFluxPlanFromContent(todoBuffer);
        if (planData) {
          const snapshot = JSON.stringify(planData);
          if (snapshot !== lastPlanSnapshot) {
            lastPlanSnapshot = snapshot;
            sendToRenderer('agent:plan', { taskId: options.taskId, planData });
          }
        }
      }

      if (
        message.type === 'tool_call'
        && message.toolInput
        && isTodoTrackingToolCall(message.toolName, message.toolInput)
      ) {
        const todoItems = extractTodoItemsFromPayload(message.toolInput);

        if (todoItems.length > 0) {
          sendToRenderer('agent:todo', { taskId: options.taskId, todoItems });
          flushTodoUpdates(options.taskId);
        }
      }

      const autoApprovePermission = Boolean(
        options.autoApprovePermissions
          && message.type === 'permission_request'
          && message.requestId,
      );

      if (workspace) {
        if (message.type === 'permission_request' && !autoApprovePermission) {
          lifecycleManager.taskStatusChanged(options.taskId, 'waiting_approval', { sessionId: session.id });
        } else if (message.type === 'question_request') {
          lifecycleManager.taskStatusChanged(options.taskId, 'waiting_input', { sessionId: session.id });
        } else if (message.type === 'result') {
          // For stream-json agents (Claude Code) the process stays alive after
          // a turn completes, so handle.on('done') only fires when the process
          // exits. Transition workspace status to 'done' here so the UI shows
          // workspace state events (Workspace is done, Checkpoint, etc.).
          lifecycleManager.taskStatusChanged(options.taskId, 'done', { sessionId: session.id });
        } else if (message.type !== 'rate_limit') {
          lifecycleManager.taskStatusChanged(options.taskId, 'running', { sessionId: session.id });
        }
      }

      // ── Turn-completion workspace operations for stream-json agents ──
      // For agents like Claude Code that keep the process alive between turns,
      // handle.on('done') only fires on process exit (stop or crash). Run the
      // same post-completion workspace operations here so that Workspace,
      // Checkpoint, and Workspace Updated events fire on turn completion.
      if (message.type === 'result' && workspace && options.mode === 'act') {
        resultCompletionDone = true;
        void (async () => {
          try {
            // 1. Detect if the agent renamed the branch
            try {
              const { stdout: actualBranch } = await execFileAsync(
                'git', ['branch', '--show-current'],
                { cwd: workspace.worktreePath, timeout: 5000 },
              );
              const trimmedBranch = actualBranch.trim();
              const freshWsBranch = workspaceStore.get(workspace.id)?.branch ?? workspace.branch;
              if (trimmedBranch && trimmedBranch !== freshWsBranch) {
                const nameSlug = trimmedBranch
                  .replace(/^[^/]*\//, '')
                  .replace(/-[a-z0-9]{4,8}$/, '')
                  .replace(/[_-]+/g, ' ')
                  .trim();
                const newName = nameSlug
                  ? nameSlug.split(' ').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ').slice(0, 40)
                  : trimmedBranch;
                workspaceStore.update(workspace.id, { branch: trimmedBranch, name: newName });
                sendToRenderer('workspace:updated', {
                  workspaceId: workspace.id,
                  branch: trimmedBranch,
                  name: newName,
                });
              }
            } catch {
              // Best-effort branch detection
            }

            // 2. Record checkpoint + outcome transition
            if (options.workspaceAction === 'merge') {
              const freshMergeWs = workspaceStore.get(workspace.id);
              if (freshMergeWs) {
                await lifecycleManager.transitionOutcome(freshMergeWs, 'task_completed_merge');
              }
              // Merge is a one-shot action — emit agent:done now so the
              // renderer finalizes the task without waiting for process exit.
              sendToRenderer('agent:done', { taskId: options.taskId });
            } else {
              await recordWorkspaceCheckpoint(workspace.id, options.prompt, session.id).catch(() => {});

              const freshWs = workspaceStore.get(workspace.id);
              if (freshWs) {
                const trigger = pendingOutcomeTrigger ?? (options.mode === 'plan' ? 'plan_completed' : 'task_completed');
                pendingOutcomeTrigger = null;
                await lifecycleManager.transitionOutcome(freshWs, trigger);
              }
            }

            // 3. Agent-driven workspace rename
            if (options.workspaceAction !== 'merge' && workspace.branch.startsWith('flux/')) {
              try {
                const currentWs = workspaceStore.get(workspace.id) ?? workspace;
                let agentName = extractAgentWorkspaceName(sessionStore, session.id);

                if (!agentName) {
                  try {
                    const { stdout: logOut } = await execFileAsync(
                      'git', ['log', '-1', '--format=%s'],
                      { cwd: currentWs.worktreePath, timeout: 5000 },
                    );
                    const commitMsg = logOut.trim();
                    if (commitMsg && !commitMsg.startsWith('[flux]')) {
                      agentName = commitMsg.slice(0, 50);
                    }
                  } catch {
                    // No commits — skip
                  }
                }

                if (agentName) {
                  const newBranch = branchNameFromLabel(agentName);
                  let nextWorktreePath = currentWs.worktreePath;

                  if (newBranch !== currentWs.branch) {
                    try {
                      await execFileAsync(
                        'git', ['branch', '-m', currentWs.branch, newBranch],
                        { cwd: currentWs.worktreePath, timeout: 10000 },
                      );
                    } catch {
                      // Branch rename failed — keep old branch
                    }

                    const renameDirName = newBranch.replace(/^flux\//, '');
                    nextWorktreePath = await moveWorktreeDirectory(
                      currentWs.parentRepo,
                      currentWs.worktreePath,
                      renameDirName,
                    );

                    workspaceStore.update(workspace.id, {
                      name: agentName,
                      branch: newBranch,
                      worktreePath: nextWorktreePath,
                    });
                    sendToRenderer('workspace:updated', {
                      workspaceId: workspace.id,
                      name: agentName,
                      branch: newBranch,
                      worktreePath: nextWorktreePath,
                    });
                  } else {
                    workspaceStore.update(workspace.id, { name: agentName });
                    sendToRenderer('workspace:updated', {
                      workspaceId: workspace.id,
                      name: agentName,
                      branch: currentWs.branch,
                    });
                  }
                }
              } catch (err) {
                console.error('[result-handler] Workspace rename failed:', err);
              }
            }

            // 4. Completion notification
            if (options.workspaceAction !== 'merge') {
              try {
                const currentWsData = workspaceStore.get(workspace.id);
                const suggestedMergeTarget = currentWsData?.baseBranch || 'main';
                sendToRenderer('workspace:completion', {
                  workspaceId: workspace.id,
                  taskId: options.taskId,
                  suggestedMergeTarget,
                });
              } catch {
                // Best-effort
              }
            }

            // 5. For merge actions, emit agent:done now. Merge is a one-shot
            //    operation — the agent won't receive follow-up prompts. For
            //    stream-json agents (Claude) the process stays alive between
            //    turns, so handle.on('done') may never fire until explicit
            //    stop. Emitting here lets the renderer finalize task state.
            if (options.workspaceAction === 'merge') {
              sendToRenderer('agent:done', { taskId: options.taskId });
              lifecycleManager.taskCompleted(options.taskId, 'done', { sessionId: session.id });
            }
          } catch (err) {
            console.error('[result-handler] Post-completion workspace ops failed:', err);
          }
        })();
      }

      if (message.type === 'permission_request') {
        if (autoApprovePermission) {
          handle.approve(message.requestId!);
          const autoApprovedMessage = {
            type: 'status',
            role: 'system',
            statusKind: 'progress',
            content: `Auto-approved ${message.toolName ?? 'permission'} for workspace merge`,
            timestamp: Date.now(),
          } satisfies AgentMessage;
          sessionStore.addMessage(session.id, toStoredMessage(autoApprovedMessage));
          sendToRenderer('agent:message', {
            taskId: options.taskId,
            message: autoApprovedMessage,
          });
        } else {
          stallMonitor.pause();
          sendToRenderer('agent:permission', {
            taskId: options.taskId,
            requestId: message.requestId,
            toolName: message.toolName ?? 'unknown',
            description: message.content,
            action: message.action,
            path: message.filePath,
          });
        }
      }
      if (!(message.type === 'permission_request' && autoApprovePermission)) {
        // Strip FLUX_WORKSPACE / legacy FLUX_WORKSPACE_LIFECYCLE lines from visible
        // message content so they don't render as raw JSON in chat cards.
        const renderedMessage = (message.content && typeof message.content === 'string')
          ? {
            ...message,
            content: stripFluxTokens(message.content),
          }
          : message;
        sendToRenderer('agent:message', { taskId: options.taskId, message: renderedMessage });
      }

      if (message.subagentId && toolHeartbeats.size > 0) {
        for (const interval of toolHeartbeats.values()) {
          clearInterval(interval);
        }
        toolHeartbeats.clear();
      }

      if (message.type === 'tool_call' && message.toolCallId) {
        const heartbeatInterval = setInterval(() => {
          sendToRenderer('agent:message', {
            taskId: options.taskId,
            message: {
              type: 'status',
              role: 'system',
              statusKind: 'progress',
              content: `Running tool: ${message.toolName ?? 'unknown'}...`,
              timestamp: Date.now(),
            } satisfies AgentMessage,
          });
        }, 15_000);
        toolHeartbeats.set(message.toolCallId, heartbeatInterval);
      }

      if (message.type === 'tool_result' && message.toolCallId) {
        const interval = toolHeartbeats.get(message.toolCallId);
        if (interval) {
          clearInterval(interval);
          toolHeartbeats.delete(message.toolCallId);
        }
      }
    });

    handle.on('done', (result) => {
      // Always clear tool heartbeats immediately to prevent leaked intervals.
      for (const interval of toolHeartbeats.values()) clearInterval(interval);
      toolHeartbeats.clear();

      void (async () => {
        // ── Guard: bail if task was already cleaned up by stop/cleanup ──
        if (!lifecycleManager.isTaskActive(options.taskId)) return;

        stallMonitor.dispose();
        taskStallMonitors.delete(options.taskId);

        if (taskIdleHeartbeats.has(options.taskId)) {
          clearInterval(taskIdleHeartbeats.get(options.taskId)!);
          taskIdleHeartbeats.delete(options.taskId);
        }

        // ── Auto-retry on crash ──
        const retryCount = taskRetryCounts.get(options.taskId) ?? 0;
        const wsIdForRetry = workspace?.id;
        if (result?.error && wsIdForRetry) {
          recordWorkspaceCrash(wsIdForRetry);
        }
        const shouldAutoRetry = result?.error
          && lifecycleManager.isTaskActive(options.taskId)
          && retryCount < MAX_AUTO_RETRIES
          && !result.error.includes('authentication')
          && !result.error.includes('rate limit')
          && !result.error.includes('timed out')
          && !result.error.startsWith('Failed to start ')  // spawn errors (binary not found) are never retriable
          && !(wsIdForRetry && isCircuitBreakerOpen(wsIdForRetry));
        if (result?.error && !shouldAutoRetry && wsIdForRetry && isCircuitBreakerOpen(wsIdForRetry)) {
          emitTaskMessage(options.taskId, session.id, {
            type: 'error',
            role: 'system',
            content: `Auto-retry disabled: too many crashes in this workspace (${CIRCUIT_BREAKER_MAX_CRASHES} in ${CIRCUIT_BREAKER_WINDOW_MS / 60000} minutes). Please investigate the underlying issue.`,
            timestamp: Date.now(),
          });
        }
        if (shouldAutoRetry) {
          taskRetryCounts.set(options.taskId, retryCount + 1);
          emitTaskMessage(options.taskId, session.id, {
            type: 'status',
            role: 'system',
            statusKind: 'progress',
            content: `Agent crashed — auto-retrying (attempt ${retryCount + 1}/${MAX_AUTO_RETRIES})...`,
            timestamp: Date.now(),
          });
          handle.removeAllListeners();
          activeTasks.delete(options.taskId);
          taskSessions.delete(options.taskId);
          await new Promise(resolve => setTimeout(resolve, recoveryDelay(retryCount)));
          // Guard after await — stop may have fired during delay
          if (!lifecycleManager.isTaskActive(options.taskId)) return;
          try {
            const context = buildConversationContext(session.id, sessionStore);
            await spawnTaskRun({
              ...options,
              sessionId: session.id,
              fallbackContext: context || undefined,
              prompt: '[Resuming previous session]',
            });
            return;
          } catch {
            // Retry failed — fall through to normal done handling
          }
        }

        // ── Normal completion ──
        cleaningUp.add(options.taskId);
        try {
          let finalError = result?.error;

          if (agentId === 'codex' && !detectedCodexSessionId) {
            const detectedSession = findLatestCodexSession(options.cwd, startedAt);
            if (detectedSession?.id) {
              detectedCodexSessionId = detectedSession.id;
              persistAgentSessionId(session.id, agentId, detectedSession.id);
            }
          }

          // ── Quality gates (with cancellation guards) ──
          if (!finalError && options.mode === 'act') {
            const commands = await resolveQualityGateCommands(options.cwd);
            const maxRetries = configManager.get().qualityGateMaxRetries ?? 2;

            for (const command of commands) {
              // Guard: stop may have fired during previous gate
              if (!lifecycleManager.isTaskActive(options.taskId)) return;

              let passed = false;
              let lastResult: { stdout: string; stderr: string; exitCode: number } = { stdout: '', stderr: '', exitCode: 0 };

              for (let attempt = 0; attempt <= maxRetries; attempt++) {
                if (!lifecycleManager.isTaskActive(options.taskId)) return;

                const gateResult = await runShellCommand(command, options.cwd, sshHost);
                passed = gateResult.exitCode === 0;
                lastResult = gateResult;

                const gateMsg: AgentMessage = {
                  type: 'quality_gate',
                  role: 'system',
                  content: passed ? `Quality gate passed: ${command}` : `Quality gate failed: ${command}`,
                  timestamp: Date.now(),
                  command,
                  exitCode: gateResult.exitCode,
                  passed,
                  stdout: gateResult.stdout,
                  stderr: gateResult.stderr,
                  retryAttempt: attempt > 0 ? attempt : undefined,
                  maxRetries: attempt > 0 ? maxRetries : undefined,
                };
                emitQualityGateMessage(options.taskId, session.id, gateMsg);

                if (passed || attempt >= maxRetries) break;

                const fixTaskId = crypto.randomUUID();
                const errorOutput = (gateResult.stderr || gateResult.stdout || '').trim();
                const fixPrompt = `The quality gate command \`${command}\` failed with these errors:\n\n\`\`\`\n${errorOutput}\n\`\`\`\n\nPlease fix these issues so the command passes.`;

                emitTaskMessage(options.taskId, session.id, {
                  type: 'status',
                  role: 'system',
                  statusKind: 'progress',
                  content: `Quality gate failed — attempting fix (${attempt + 1}/${maxRetries})...`,
                  timestamp: Date.now(),
                });

                const fixHandle = agentManager.spawn(agentId, {
                  taskId: fixTaskId,
                  prompt: fixPrompt,
                  cwd: spawnOptions.cwd,
                  mode: 'act',
                  model: spawnOptions.model,
                  binaryPath: spawnOptions.binaryPath,
                  sshHost: spawnOptions.sshHost,
                  remoteCwd: spawnOptions.remoteCwd,
                }, undefined);

                await new Promise<void>((resolve) => {
                  const safetyTimer = setTimeout(() => {
                    fixHandle.removeAllListeners();
                    resolve();
                  }, 360_000);

                  fixHandle.on('message', (msg: AgentMessage) => {
                    if (msg.type === 'permission_request' && msg.requestId) {
                      fixHandle.approve(msg.requestId);
                    } else if (msg.type !== 'result' && msg.type !== 'rate_limit') {
                      emitTaskMessage(options.taskId, session.id, msg);
                    }
                  });

                  fixHandle.on('done', () => {
                    clearTimeout(safetyTimer);
                    fixHandle.removeAllListeners();
                    resolve();
                  });
                });
              }

              if (!passed) {
                const baselinePassed = qualityGateBaseline.get(command);
                if (baselinePassed === false) {
                  const preExistingMsg: AgentMessage = {
                    type: 'quality_gate',
                    role: 'system',
                    content: `Quality gate pre-existing failure (existed before agent ran): ${command}`,
                    timestamp: Date.now(),
                    command,
                    exitCode: lastResult.exitCode,
                    passed: false,
                    isPreExisting: true,
                    stdout: lastResult.stdout,
                    stderr: lastResult.stderr,
                  };
                  emitQualityGateMessage(options.taskId, session.id, preExistingMsg);
                } else {
                  finalError = `Quality gate failed: ${command}`;
                  break;
                }
              }
            }
          }

          // Guard: stop may have fired during quality gates
          if (!lifecycleManager.isTaskActive(options.taskId)) return;

          // ── Diff capture ──
          if (preRunRef && !sshHost) {
            try {
              const diffData = await captureGitDiff(options.cwd, preRunRef);
              if (diffData && diffData.files.length > 0) {
                const msgCount = (await (() => {
                  try { return sessionStore.getMessages(session.id).length; } catch { return 0; }
                })());
                const key = `0-${msgCount}`;
                sendToRenderer('agent:diff', {
                  taskId: options.taskId,
                  key,
                  diff: diffData,
                });
              }
            } catch {
              // Diff capture is best-effort
            }
          }

          // Guard: stop may have fired during diff capture
          if (!lifecycleManager.isTaskActive(options.taskId)) return;

          // ── Emit done + update workspace state ──
          const doneErrorKind = finalError ? classifyErrorContent(finalError)?.errorKind : undefined;
          sendToRenderer('agent:done', { taskId: options.taskId, error: finalError, errorKind: doneErrorKind });

          if (workspace) {
            const nextStatus: WorkspaceStatus = finalError ? 'error' : 'done';
            lifecycleManager.taskCompleted(options.taskId, nextStatus, { sessionId: session.id });

            // Skip post-completion ops if already run during result-message
            // handling (stream-json agents like Claude Code). The done handler
            // still runs quality gates and diff capture above, but branch
            // detection, checkpoint, rename, and completion notification were
            // already emitted on turn completion.
            //
            // Exception: for merge actions, always retry the outcome transition
            // as a safety net — the result handler's transition may have failed
            // silently (e.g. git state resolution error caught by try/catch).
            if (resultCompletionDone && !finalError) {
              // Safety-net: retry merge outcome transition in case it failed
              // during the result handler. transitionOutcome is idempotent —
              // if the outcome is already 'merged', this is a no-op.
              if (options.workspaceAction === 'merge' && options.mode === 'act') {
                try {
                  const freshMergeWs = workspaceStore.get(workspace.id) ?? workspace;
                  await lifecycleManager.transitionOutcome(freshMergeWs, 'task_completed_merge');
                } catch (err) {
                  console.error('[done-handler] Merge outcome retry failed:', err);
                }
              }
              // Skip remaining post-completion ops — already handled
            } else {

            // Post-completion operations: branch detection, outcome transition,
            // checkpoint recording, rename, completion notification.
            // Each operation is individually guarded so a failure in one
            // doesn't block the others or prevent the finally cleanup.

            // 1. Detect if the agent renamed the branch
            try {
              const { stdout: actualBranch } = await execFileAsync(
                'git', ['branch', '--show-current'],
                { cwd: workspace.worktreePath, timeout: 5000 },
              );
              const trimmedBranch = actualBranch.trim();
              if (trimmedBranch && trimmedBranch !== workspace.branch) {
                const nameSlug = trimmedBranch
                  .replace(/^[^/]*\//, '')
                  .replace(/-[a-z0-9]{4,8}$/, '')
                  .replace(/[_-]+/g, ' ')
                  .trim();
                const newName = nameSlug
                  ? nameSlug.split(' ').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ').slice(0, 40)
                  : trimmedBranch;
                workspaceStore.update(workspace.id, { branch: trimmedBranch, name: newName });
                sendToRenderer('workspace:updated', {
                  workspaceId: workspace.id,
                  branch: trimmedBranch,
                  name: newName,
                });
              }
            } catch {
              // Best-effort branch detection
            }

            if (options.mode === 'act') {
              // 2. Outcome transition
              try {
                if (options.workspaceAction === 'merge') {
                  if (!finalError) {
                    const freshMergeWs = workspaceStore.get(workspace.id) ?? workspace;
                    await lifecycleManager.transitionOutcome(freshMergeWs, 'task_completed_merge');
                  }
                } else {
                  if (!finalError) {
                    await recordWorkspaceCheckpoint(workspace.id, options.prompt, session.id).catch(() => {});
                  }

                  const freshWs = workspaceStore.get(workspace.id);
                  if (freshWs) {
                    const trigger = finalError ? 'task_error' : (pendingOutcomeTrigger ?? 'task_completed');
                    pendingOutcomeTrigger = null;
                    await lifecycleManager.transitionOutcome(freshWs, trigger);
                  }
                }
              } catch (err) {
                console.error('[done-handler] Outcome transition failed:', err);
              }

              // 3. Agent-driven workspace rename
              if (options.workspaceAction !== 'merge' && !finalError && workspace.branch.startsWith('flux/')) {
                try {
                  const currentWs = workspaceStore.get(workspace.id) ?? workspace;
                  let agentName = extractAgentWorkspaceName(sessionStore, session.id);

                  if (!agentName) {
                    try {
                      const { stdout: logOut } = await execFileAsync(
                        'git', ['log', '-1', '--format=%s'],
                        { cwd: currentWs.worktreePath, timeout: 5000 },
                      );
                      const commitMsg = logOut.trim();
                      if (commitMsg && !commitMsg.startsWith('[flux]')) {
                        agentName = commitMsg.slice(0, 50);
                      }
                    } catch {
                      // No commits — skip
                    }
                  }

                  if (agentName) {
                    const newBranch = branchNameFromLabel(agentName);
                    let nextWorktreePath = currentWs.worktreePath;

                    if (newBranch !== currentWs.branch) {
                      try {
                        await execFileAsync(
                          'git', ['branch', '-m', currentWs.branch, newBranch],
                          { cwd: currentWs.worktreePath, timeout: 10000 },
                        );
                      } catch {
                        // Branch rename failed — keep old branch
                      }

                      const renameDirName = newBranch.replace(/^flux\//, '');
                      nextWorktreePath = await moveWorktreeDirectory(
                        currentWs.parentRepo,
                        currentWs.worktreePath,
                        renameDirName,
                      );

                      workspaceStore.update(workspace.id, {
                        name: agentName,
                        branch: newBranch,
                        worktreePath: nextWorktreePath,
                      });
                      sendToRenderer('workspace:updated', {
                        workspaceId: workspace.id,
                        name: agentName,
                        branch: newBranch,
                        worktreePath: nextWorktreePath,
                      });
                    } else {
                      workspaceStore.update(workspace.id, { name: agentName });
                      sendToRenderer('workspace:updated', {
                        workspaceId: workspace.id,
                        name: agentName,
                        branch: currentWs.branch,
                      });
                    }
                  }
                } catch (err) {
                  console.error('[done-handler] Workspace rename failed:', err);
                }
              }

              // 4. Completion notification
              if (options.workspaceAction !== 'merge') {
                try {
                  const currentWsData = workspaceStore.get(workspace.id);
                  const suggestedMergeTarget = currentWsData?.baseBranch || 'main';
                  sendToRenderer('workspace:completion', {
                    workspaceId: workspace.id,
                    taskId: options.taskId,
                    suggestedMergeTarget,
                  });
                } catch {
                  // Best-effort
                }
              }
            }

            } // end: resultCompletionDone else
          }
        } finally {
          // Canonical cleanup — releaseTask is idempotent so safe even if
          // stop already cleaned up during an earlier guard check.
          releaseTask(options.taskId);
          lifecycleManager.taskReleased(options.taskId);
        }
      })();
    });

    return { taskId: options.taskId, session: sessionStore.get(session.id) ?? session };
  };

  // --- Task IPC handlers ---

  ipcMain.handle(
    'task:spawn',
    async (
      _event,
      options: SpawnTaskRunOptions,
    ) => {
      return spawnTaskRun(options);
    },
  );

  ipcMain.handle('task:stop', async (_event, { taskId }: { taskId: string }) => {
    requireFields({ taskId }, 'taskId');
    if (!lifecycleManager.isTaskActive(taskId) && !activeTasks.has(taskId)) return;
    releaseTask(taskId);
    sendToRenderer('agent:done', { taskId, error: undefined });
    lifecycleManager.taskReleasedWithStatus(taskId, 'done');
  });

  const restartingTasks = new Set<string>();

  ipcMain.handle('task:restart', async (_event, { taskId }: { taskId: string }) => {
    requireFields({ taskId }, 'taskId');

    // Guard against concurrent restarts (e.g. rapid double-click)
    if (restartingTasks.has(taskId)) return;
    restartingTasks.add(taskId);

    try {
      const sessionId = taskSessions.get(taskId);
      if (!sessionId) throw new Error('No session for task');
      const session = sessionStore.get(sessionId);
      if (!session) throw new Error('Session not found');

      // Clean up current run but preserve lifecycle manager state
      // (the task is being restarted, not truly released)
      releaseTask(taskId);

      await new Promise(resolve => setTimeout(resolve, RECOVERY_DELAY_MS));

      const context = buildConversationContext(sessionId, sessionStore);
      return await spawnTaskRun({
        taskId,
        sessionId,
        prompt: '[Resuming previous session]',
        cwd: session.cwd,
        mode: session.mode as 'plan' | 'act',
        model: session.model,
        agentId: session.agentId,
        fallbackContext: context || undefined,
      });
    } finally {
      restartingTasks.delete(taskId);
    }
  });

  ipcMain.handle('subagent:spawn', async (_event, options: {
    parentTaskId: string;
    prompt: string;
    model?: string;
    name: string;
    cwd?: string;
  }) => {
    requireFields(options as unknown as Record<string, unknown>, 'parentTaskId', 'prompt', 'name');

    const parentHandle = activeTasks.get(options.parentTaskId);
    if (!parentHandle) {
      throw new Error(`Task ${options.parentTaskId} does not have an active run`);
    }

    const parentSessionId = taskSessions.get(options.parentTaskId);
    const parentSession = parentSessionId ? sessionStore.get(parentSessionId) : null;
    const parentAgentId = parentHandle.agentId;
    const config = configManager.get();
    const model = options.model || config.subagentModel || parentSession?.model || config.defaultModel;
    const subagentId = `${options.parentTaskId}:sub-${crypto.randomUUID().slice(0, 8)}`;
    const session = sessionStore.create({
      title: `[Subagent] ${options.name}`,
      agentId: parentAgentId,
      model,
      mode: 'plan',
      cwd: options.cwd ?? parentSession?.cwd ?? getCurrentCwd(),
      metadata: {
        parentTaskId: options.parentTaskId,
        subagentId,
        subagentName: options.name,
      },
    });

    const subSpawnOptions: SpawnOptions = {
      taskId: subagentId,
      prompt: options.prompt,
      model,
      mode: 'plan',
      thinking: 'low',
      cwd: options.cwd ?? parentSession?.cwd ?? getCurrentCwd(),
      sessionId: parentAgentId === 'claude-code' ? session.id : undefined,
      parentTaskId: options.parentTaskId,
      subagentName: options.name,
    };

    let subHandle: AgentHandle;
    try {
      subHandle = agentManager.spawn(parentAgentId, subSpawnOptions);
    } catch (error) {
      sessionStore.delete(session.id);
      throw error;
    }

    activeTasks.set(subagentId, subHandle);
    taskSessions.set(subagentId, session.id);
    activeSubagents.set(subagentId, {
      parentTaskId: options.parentTaskId,
      handle: subHandle,
      name: options.name,
      toolCount: 0,
      inputTokens: 0,
      outputTokens: 0,
      sessionId: session.id,
    });

    emitSubagentMessage(options.parentTaskId, subagentId, options.name, {
      type: 'status',
      role: 'system',
      content: options.name,
      timestamp: Date.now(),
      statusKind: 'spawn',
      subagentStatus: 'spawning',
      subagentToolCount: 0,
      subagentTokens: {
        input: 0,
        output: 0,
      },
    });

    subHandle.on('session-meta', (meta) => {
      if (!meta || typeof meta !== 'object') return;
      const sessionMeta = meta as { id?: string };
      if (typeof sessionMeta.id !== 'string') return;
      persistAgentSessionId(session.id, parentAgentId, sessionMeta.id);
    });

    subHandle.on('message', (message) => {
      const subagent = activeSubagents.get(subagentId);
      if (!subagent) return;

      if (message.type === 'tool_call') {
        subagent.toolCount += 1;
      }
      if (message.type === 'result') {
        subagent.inputTokens += message.inputTokens ?? 0;
        subagent.outputTokens += message.outputTokens ?? 0;
      }

      sessionStore.addMessage(session.id, toStoredMessage(message));
      emitSubagentMessage(options.parentTaskId, subagentId, options.name, {
        ...message,
        subagentToolCount: subagent.toolCount,
        subagentTokens: {
          input: subagent.inputTokens,
          output: subagent.outputTokens,
        },
      });
    });

    subHandle.on('done', (result) => {
      const subagent = activeSubagents.get(subagentId);
      if (!subagent) return;

      emitSubagentMessage(options.parentTaskId, subagentId, options.name, {
        type: 'status',
        role: 'system',
        content: result?.error ? `${options.name} failed` : `${options.name} finished`,
        timestamp: Date.now(),
        statusKind: 'progress',
        subagentStatus: result?.error ? 'error' : 'done',
        subagentToolCount: subagent.toolCount,
        subagentTokens: {
          input: subagent.inputTokens,
          output: subagent.outputTokens,
        },
      });

      subHandle.removeAllListeners();
      activeSubagents.delete(subagentId);
      activeTasks.delete(subagentId);
      taskSessions.delete(subagentId);
    });

    return { subagentId };
  });

  ipcMain.handle('subagent:stop', async (_event, { subagentId, parentTaskId }: { subagentId?: string; parentTaskId?: string }) => {
    const SUBAGENT_STOP_TIMEOUT_MS = 10_000;
    const targets = subagentId
      ? [subagentId]
      : Array.from(activeSubagents.entries())
        .filter(([, subagent]) => !parentTaskId || subagent.parentTaskId === parentTaskId)
        .map(([id]) => id);

    for (const targetId of targets) {
      const subagent = activeSubagents.get(targetId);
      if (!subagent) continue;
      // Use a timeout to prevent hanging indefinitely on a wedged subagent
      await Promise.race([
        subagent.handle.stop(),
        new Promise<void>(resolve => setTimeout(resolve, SUBAGENT_STOP_TIMEOUT_MS)),
      ]);
      subagent.handle.removeAllListeners();
      activeSubagents.delete(targetId);
      activeTasks.delete(targetId);
      taskSessions.delete(targetId);
      emitSubagentMessage(subagent.parentTaskId, targetId, subagent.name, {
        type: 'status',
        role: 'system',
        content: `${subagent.name} stopped`,
        timestamp: Date.now(),
        statusKind: 'progress',
        subagentStatus: 'error',
        subagentToolCount: subagent.toolCount,
        subagentTokens: {
          input: subagent.inputTokens,
          output: subagent.outputTokens,
        },
      });
    }
  });

  ipcMain.handle('task:approve', async (_event, { taskId, requestId }: { taskId: string; requestId: string }) => {
    const handle = activeTasks.get(taskId);
    if (handle) handle.approve(requestId);
    taskStallMonitors.get(taskId)?.resume();
  });

  ipcMain.handle('task:deny', async (_event, { taskId, requestId }: { taskId: string; requestId: string }) => {
    const handle = activeTasks.get(taskId);
    if (handle) handle.deny(requestId);
    taskStallMonitors.get(taskId)?.resume();
  });

  ipcMain.handle('task:answer-question', async (_event, { taskId, requestId, response }: {
    taskId: string;
    requestId: string;
    response: string;
  }) => {
    requireFields({ taskId, requestId, response }, 'taskId', 'requestId', 'response');
    const handle = activeTasks.get(taskId);
    if (!handle) {
      throw new Error(`Task ${taskId} does not have an active run`);
    }

    if (!handle.isAlive()) {
      throw new Error('Agent process has exited — answer cannot be delivered');
    }

    const sessionId = taskSessions.get(taskId);
    if (sessionId) {
      emitTaskMessage(taskId, sessionId, buildUserMessagePayload(response));
    }

    const workspaceId = lifecycleManager.getWorkspaceForTask(taskId);
    if (workspaceId) {
      lifecycleManager.taskStatusChanged(taskId, 'running', sessionId ? { sessionId } : undefined);
    }

    handle.answerQuestion(requestId, response);
    taskStallMonitors.get(taskId)?.resume();
  });

  ipcMain.handle('task:steer', async (_event, { taskId, prompt, images, attachments }: { taskId: string; prompt: string; images?: string[]; attachments?: FileAttachment[] }) => {
    const handle = activeTasks.get(taskId);
    if (!handle) {
      return { steerFailed: true, reason: 'task_finished' };
    }

    if (!handle.isAlive()) {
      return { steerFailed: true, reason: 'process_exited' };
    }

    let effectivePrompt = await buildPromptWithAttachments(prompt, attachments, getSshHost());

    // Inject workspace skills on follow-up messages so the agent retains
    // lifecycle protocol context across the full conversation.
    const workspaceId = lifecycleManager.getWorkspaceForTask(taskId);
    if (workspaceId) {
      const workspace = workspaceStore.get(workspaceId);
      if (workspace) {
        const wsContext = buildWorkspaceSystemContext(workspace, workspace.mode, undefined, workspace.agentId, true);
        if (wsContext) {
          effectivePrompt = `${wsContext}\n\n${effectivePrompt}`;
        }
      }
    }

    handle.steer(effectivePrompt, images);

    const sessionId = taskSessions.get(taskId);
    if (sessionId) {
      sessionStore.addMessage(
        sessionId,
        buildStoredUserMessage(prompt, images, attachments),
      );
    }
    return { steerFailed: false };
  });

  return { spawnTaskRun, releaseTask };
}
